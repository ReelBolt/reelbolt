import { DIFFERENT_ACTIONS, FAILED_ACTIONS } from './reconcile.mjs';
import { STRIPE_API_VERSION } from './stripe-client.mjs';

const PRICE_PLACEHOLDER = 'price_<would-create>';
const PORTAL_PLACEHOLDER = 'bpc_<would-create>';

function sqlText(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}

function usable(entry) {
  return entry && !entry.error && !FAILED_ACTIONS.has(entry.action) && entry.action !== 'skip';
}

function priceId(entry) {
  return usable(entry) ? (entry.id ?? PRICE_PLACEHOLDER) : null;
}

/** The new provider's price ids a promotion applies to; prices without a usable id are left out. */
function targetPriceIdsOf(targets, plans, topups) {
  if (!targets) {
    return [];
  }
  const found =
    targets.kind === 'plan'
      ? targets.planKeys.map((key) => plans.find((p) => p.planId === key)?.monthly)
      : targets.packCredits.map((credits) => topups.find((p) => p.credits === credits)?.price);
  return [...new Set(found.filter(Boolean))];
}

/** Collect the ids our database and env need, with placeholders for what a dry run would create. */
export function collectIds(items, desired, promotions) {
  const byKey = new Map(items.filter((i) => i.kind === 'price' && !i.key.includes(' (')).map((i) => [i.key, i]));
  const plans = desired.plans.map((plan) => ({ planId: plan.planId, monthly: priceId(byKey.get(plan.lookupKey)),
    annual: plan.annual ? priceId(byKey.get(plan.annual.lookupKey)) : null,
  }));
  const topups = desired.packs.map((pack) => ({ credits: pack.credits, price: priceId(byKey.get(pack.lookupKey)) }));
  const portalItem = items.find((i) => i.kind === 'portal');
  const portal = usable(portalItem) ? (portalItem.id ?? PORTAL_PLACEHOLDER) : null;
  const coupons = [];
  for (const promo of promotions?.eligible ?? []) {
    const entry = items.find((i) => i.kind === 'coupon' && i.key === promo.couponId);
    // A drifted coupon does not match our definition, so the database must not point at it.
    if (usable(entry) && entry.action !== 'drift') {
      coupons.push({
        promotionId: promo.promotionId,
        couponId: entry.id ?? promo.couponId,
        founder: Boolean(promo.founder),
        targetPriceIds: targetPriceIdsOf(promo.targets, plans, topups),
      });
    }
  }
  return { plans, topups, portal, coupons };
}

export function renderSql(ids, { dryRun }) {
  const lines = [];
  lines.push(`-- Generated by stripe-catalog-sync (${dryRun ? 'DRY RUN, <would-create> are placeholders, NOT FOR EXECUTION' : 'applied'}). Review, then run with psql.`);
  lines.push('-- The "stripe" key is merged into provider_price_ids_json; other providers (paddle) are kept.');
  lines.push('-- Promotion targets: the Stripe price ids are UNIONED into target_price_ids_json; existing (paddle) ids are kept.');
  lines.push('BEGIN;');
  if (dryRun) {
    // Placeholders are not real ids. If someone pipes this into psql by mistake, the failed
    // statement aborts the transaction and COMMIT rolls everything back.
    lines.push("DO $$ BEGIN RAISE EXCEPTION 'dry-run output contains placeholders: do not execute'; END $$;");
  }
  for (const plan of ids.plans) {
    if (!plan.monthly) {
      lines.push(`-- plan ${plan.planId}: no usable Stripe price, no statement`);
      continue;
    }
    const value = JSON.stringify({ monthly: plan.monthly, annual: plan.annual ?? null });
    lines.push(
      `UPDATE plans SET provider_price_ids_json = jsonb_set(COALESCE(provider_price_ids_json,'{}'::jsonb), '{stripe}', ${sqlText(value)}::jsonb, true) WHERE key = ${sqlText(plan.planId)};`,
    );
  }
  for (const coupon of ids.coupons) {
    if (!coupon.promotionId) {
      lines.push(`-- NOTE: the founder price coupon is ${coupon.couponId}. Point the founder promotion row at it: re-run with --founder-promotion-id <uuid>, or UPDATE promotions SET provider_discount_id = ${sqlText(coupon.couponId)} WHERE id = '<founder promotion uuid>';`);
      continue;
    }
    lines.push(`UPDATE promotions SET provider_discount_id = ${sqlText(coupon.couponId)} WHERE id = ${sqlText(coupon.promotionId)};`);
    if (coupon.targetPriceIds.length === 0) {
      lines.push(`-- NOTE: promotion ${coupon.promotionId} has no resolvable Stripe price to target (its plan or pack prices were skipped or failed): target_price_ids_json is left as it is, so it will not apply to Stripe checkouts until the prices exist and this tool is run again.`);
      continue;
    }
    // target_price_ids_json is jsonb holding an array of provider price ids that PromotionService
    // matches a checkout price against. Union, never replace: the old provider's ids stay (so the
    // promotion still works for any customer who is still on that provider), duplicates collapse.
    // A value that is not an array is treated as empty rather than failing the whole script.
    const additions = sqlText(JSON.stringify(coupon.targetPriceIds));
    lines.push(
      `UPDATE promotions SET target_price_ids_json = (SELECT COALESCE(jsonb_agg(DISTINCT v ORDER BY v), '[]'::jsonb) FROM jsonb_array_elements_text((CASE WHEN jsonb_typeof(target_price_ids_json) = 'array' THEN target_price_ids_json ELSE '[]'::jsonb END) || ${additions}::jsonb) AS t(v)) WHERE id = ${sqlText(coupon.promotionId)};`,
    );
  }
  lines.push('COMMIT;');
  return `${lines.join('\n')}\n`;
}

export function renderEnv(ids) {
  const lines = [];
  for (const plan of ids.plans) {
    if (plan.annual) {
      lines.push(`STRIPE_PLAN_${plan.planId.toUpperCase().replace(/[^A-Z0-9]/g, '_')}_ANNUAL_PRICE=${plan.annual}`);
    }
  }
  for (const pack of ids.topups) {
    lines.push(pack.price ? `STRIPE_TOPUP_PRICE_${pack.credits}=${pack.price}` : `# top-up ${pack.credits}: no usable Stripe price`);
  }
  lines.push(ids.portal ? `STRIPE_PORTAL_CONFIGURATION_ID=${ids.portal}` : '# portal: not synced (--skip-portal or an error)');
  return `${lines.join('\n')}\n`;
}

export function renderTable(items) {
  const rows = [['ACTION', 'OBJECT', 'KEY', 'DETAIL'], ...items.map((i) => [i.error ? 'error' : i.action, i.kind, i.key, i.error ?? `${i.detail ?? ''}${i.applied ? ' [applied]' : ''}`])];
  const widths = [0, 1, 2].map((col) => Math.max(...rows.map((r) => r[col].length)));
  return `${rows.map((r) => `${r[0].padEnd(widths[0])}  ${r[1].padEnd(widths[1])}  ${r[2].padEnd(widths[2])}  ${r[3]}`).join('\n')}\n`;
}

export function summarize(items, { apply }) {
  const counts = {};
  for (const entry of items) {
    const name = entry.error ? 'error' : entry.action;
    counts[name] = (counts[name] ?? 0) + 1;
  }
  const errors = items.filter((i) => i.error || FAILED_ACTIONS.has(i.action)).length;
  const differences = apply
    ? items.some((i) => i.action === 'drift' && !i.applied)
    : items.some((i) => DIFFERENT_ACTIONS.has(i.action));
  return { counts, errors, differences };
}

export function buildReport({ items, ids, summary, mode, apply, currency }) {
  return {
    schema: 1,
    apiVersion: STRIPE_API_VERSION,
    mode,
    dryRun: !apply,
    currency,
    summary: { ...summary.counts, errors: summary.errors, inSync: !summary.differences && summary.errors === 0 },
    ids,
    items: items.map((i) => ({
      object: i.kind,
      key: i.key,
      action: i.error ? 'error' : i.action,
      detail: i.detail ?? null,
      id: i.id ?? null,
      ...(i.error ? { error: i.error } : {}),
    })),
  };
}
