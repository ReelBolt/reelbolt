// Renders the ReelBolt cursor masters from their SVG sources.
//
//   node brand/scripts/cursors.mjs          write brand/cursors/*.png and cursors.manifest.json
//
// The SVG sources under brand/cursors/src/ are the artwork; the PNGs are generated artefacts and
// must never be edited by hand. A PNG master whose bytes do not match the SVG it came from is
// reported by `node brand/scripts/sync.mjs --check` through the manifest this script writes.
//
// Palette and geometry live in the SVGs; the manifest (brand/cursors/cursors.json) carries the
// contract the app consumes: hotspot in 32 px space, fallback keyword, intent. See
// docs/design/cursors.md.
import { createHash } from 'node:crypto';
import { readFile, writeFile, readdir, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import sharp from 'sharp';

const brandDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const cursorsDir = path.join(brandDir, 'cursors');
const srcDir = path.join(cursorsDir, 'src');

const sha256 = (buf) => createHash('sha256').update(buf).digest('hex');

const manifest = JSON.parse(await readFile(path.join(cursorsDir, 'cursors.json'), 'utf8'));
const listed = new Set(manifest.cursors.map((c) => c.name));
const sources = [...(await readdir(srcDir))]
  .filter((f) => f.endsWith('.svg'))
  .map((f) => f.slice(0, -4))
  .sort();

const unknownSource = sources.filter((name) => !listed.has(name));
const missingSource = [...listed].filter((name) => !sources.includes(name));
if (unknownSource.length || missingSource.length) {
  if (unknownSource.length) console.error(`cursors: SVG with no manifest entry: ${unknownSource.join(', ')}`);
  if (missingSource.length) console.error(`cursors: manifest entry with no SVG: ${missingSource.join(', ')}`);
  process.exit(1);
}

await mkdir(cursorsDir, { recursive: true });

const outputs = [];
const sourcesHash = {};

for (const cursor of manifest.cursors) {
  const svgPath = path.join(srcDir, `${cursor.name}.svg`);
  const svg = await readFile(svgPath);
  sourcesHash[`cursors/src/${cursor.name}.svg`] = sha256(svg);

  for (const scale of manifest.scales) {
    const file = scale.suffix ? `${cursor.name}${scale.suffix}.png` : `${cursor.name}.png`;
    const out = path.join(cursorsDir, file);
    // Render large and downscale so 32 px edges stay crisp: librsvg gives clean AA at 12x.
    const got = await sharp(svg, { density: 72 * 12 })
      .resize(scale.px, scale.px, {
        fit: 'contain',
        background: { r: 0, g: 0, b: 0, alpha: 0 },
        kernel: 'lanczos3',
      })
      .png({ compressionLevel: 9, palette: false })
      .toBuffer();
    await writeFile(out, got);
    outputs.push({ file, sha256: sha256(got), px: scale.px });
  }
  process.stdout.write(`rendered ${cursor.name}\n`);
}

outputs.sort((a, b) => a.file.localeCompare(b.file));
const provenance = {
  $comment: 'Generated by brand/scripts/cursors.mjs. Do not edit — regenerate instead.',
  generator: 'brand/scripts/cursors.mjs',
  sources: sourcesHash,
  outputs,
};
await writeFile(
  path.join(cursorsDir, 'cursors.manifest.json'),
  `${JSON.stringify(provenance, null, 2)}\n`,
);

console.log(`\n${manifest.cursors.length} cursors, ${outputs.length} PNGs written.`);
