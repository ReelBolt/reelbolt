#!/usr/bin/env node
// Builds inference/blocks/catalog.json from src/<id>/block.json + the files on disk, computes
// sha256s, validates ids/paths/requires, and regenerates the skill's CATALOG.md summary.
//   node scripts/build-catalog.mjs          write catalog.json and CATALOG.md
//   node scripts/build-catalog.mjs --check  fail if either file is stale (CI)
// It also rewrites (or, with --check, verifies) the block list between the [[BLOCKS:BEGIN]] / [[BLOCKS:END]]
// marker lines in the agent prompts (PROMPT_FILES), so the prompts cannot drift from catalog.json.
import fs from 'node:fs';
import path from 'node:path';
import {BLOCKS_ROOT, REPO_ROOT, CATEGORIES, loadAvailablePackages, sha256, validateCatalog} from './lib.mjs';

const check = process.argv.includes('--check');
const available = loadAvailablePackages();
const srcRoot = path.join(BLOCKS_ROOT, 'src');

const walk = (dir) => fs.readdirSync(dir, {withFileTypes: true}).flatMap((e) =>
  e.isDirectory() ? walk(path.join(dir, e.name)) : [path.join(dir, e.name)]);

const blocks = [];
for (const entry of fs.readdirSync(srcRoot, {withFileTypes: true}).filter((e) => e.isDirectory() && e.name !== '_shared').sort((a, b) => a.name.localeCompare(b.name))) {
  const meta = JSON.parse(fs.readFileSync(path.join(srcRoot, entry.name, 'block.json'), 'utf8'));
  if (meta.id !== entry.name) throw new Error(`${entry.name}/block.json: id "${meta.id}" must equal the directory name`);
  const own = walk(path.join(srcRoot, entry.name))
    .map((abs) => path.relative(srcRoot, abs).split(path.sep).join('/'))
    .filter((p) => !p.endsWith('/block.json'));
  const paths = [...new Set([...own, ...(meta.sharedFiles ?? [])])].sort();
  const files = paths.map((p) => {
    const abs = path.join(srcRoot, p);
    if (!fs.existsSync(abs)) throw new Error(`${meta.id}: file ${p} does not exist`);
    return {path: p, sha256: sha256(fs.readFileSync(abs))};
  });
  const requires = (meta.requires ?? []).map((name) => ({name, version: available.get(name) ?? ''}));
  blocks.push({
    id: meta.id, version: meta.version, title: meta.title, category: meta.category, description: meta.description,
    tags: meta.tags ?? [], requires, files,
    previewComposition: {...meta.previewComposition, file: `previews/${meta.id}.tsx`},
    props: meta.props, example: meta.example,
  });
}
blocks.sort((a, b) => a.category.localeCompare(b.category) || a.id.localeCompare(b.id));
const catalog = {schemaVersion: 1, blocks};

const problems = validateCatalog(catalog, available);
if (problems.length) { console.error(problems.join('\n')); process.exit(1); }

let md = '# Block catalog (generated by inference/blocks/scripts/build-catalog.mjs; do not edit)\n\n';
md += `${blocks.length} block(s). Call ListBlocks(category?, query?) for the live list, GetBlock(id) for props, AddBlock(id) to copy one into src/blocks/<id>/.\n`;
for (const cat of CATEGORIES) {
  const inCat = blocks.filter((b) => b.category === cat);
  if (inCat.length === 0) continue;
  md += `\n## ${cat}\n\n`;
  for (const b of inCat) md += `- \`${b.id}\`: ${b.title}. ${b.description}\n`;
}

// One line per block: first sentence of the description, "Use for/to" dropped, at most ~110 chars.
const blurb = (d) => {
  let t = d.replace(/^Use (for|to) /, '').split(/\.(\s|$)/)[0].trim();
  if (t.length > 110) {
    const head = t.slice(0, 110);
    const semi = head.lastIndexOf('; ');
    const clause = semi >= 40 ? semi : head.lastIndexOf(', ');
    t = clause >= 40 ? head.slice(0, clause) : head.replace(/\s+\S*$/, '');
    t = t.replace(/(\s+(and|or|to|for|the|a|an|with|of|in|on|by|as|at))+$/i, '').replace(/[\s,;:(-]+$/, '');
  }
  return t;
};
const promptLines = ['Blocks you can add with AddBlock (id: what it does):'];
for (const cat of CATEGORIES) {
  const inCat = blocks.filter((b) => b.category === cat);
  if (inCat.length === 0) continue;
  promptLines.push(`${cat}:`);
  for (const b of inCat) promptLines.push(`- ${b.id}: ${blurb(b.description)}`);
}
const PROMPT_FILES = [
  'Agents/Production/AuthorAgent.cs', 'Agents/Production/CompositionReviserAgent.cs',
  'Agents/Production/MotionGraphicsPlannerAgent.cs', 'Agents/Production/MotionGraphicsDirectorAgent.cs',
  'Agents/Production/GraphicDesignerAgent.cs',
].map((f) => path.join(REPO_ROOT, 'inference', 'src', 'ReelBolt.WorkflowEngine', f))
  .concat(path.join(REPO_ROOT, 'inference', 'src', 'ReelBolt.Inference.Api', 'Data', 'DatabaseSeeder.cs'));
const regionRe = /^([ \t]*)\[\[BLOCKS:BEGIN\]\]\n[\s\S]*?^[ \t]*\[\[BLOCKS:END\]\]$/gm;
const render = (text) => text.replace(regionRe, (_m, ind) =>
  `${ind}[[BLOCKS:BEGIN]]\n${promptLines.map((l) => ind + l).join('\n')}\n${ind}[[BLOCKS:END]]`);
const stalePrompts = PROMPT_FILES.filter((f) => fs.readFileSync(f, 'utf8') !== render(fs.readFileSync(f, 'utf8')));
const json = JSON.stringify(catalog, null, 2) + '\n';
const mdPath = path.join(REPO_ROOT, 'inference', 'skills', 'reelbolt-blocks', 'CATALOG.md');
const jsonPath = path.join(BLOCKS_ROOT, 'catalog.json');
const same = (p, c) => fs.existsSync(p) && fs.readFileSync(p, 'utf8') === c;
if (check) {
  if (!same(jsonPath, json) || !same(mdPath, md) || stalePrompts.length) { console.error('catalog.json, CATALOG.md or a prompt block list is stale: run node scripts/build-catalog.mjs' + stalePrompts.map((f) => `\n  ${f}`).join('')); process.exit(1); }
  console.log('catalog up to date');
} else {
  fs.mkdirSync(path.dirname(mdPath), {recursive: true});
  fs.writeFileSync(jsonPath, json);
  fs.writeFileSync(mdPath, md);
  for (const f of PROMPT_FILES) fs.writeFileSync(f, render(fs.readFileSync(f, 'utf8')));
  console.log(`wrote catalog.json (${blocks.length} blocks) and CATALOG.md`);
}
