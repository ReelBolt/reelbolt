namespace ReelBolt.WorkflowEngine.Tests;

/// <summary>
/// Environment-gated, end-to-end check of cloning against a REAL self-hosted fish-speech server and
/// a REAL OpenAI-compatible transcription server: the real <see cref="ProjectVoicesController"/>
/// (in-memory database, mocked object store), the real <see cref="SpeechSynthesisClientFactory"/>
/// and <see cref="TranscriptionClientFactory"/>, no HTTP mocks.
///
/// <para>
/// The reference recording is SYNTHETIC — the server's own default voice reading a fixed sentence —
/// so no real person's voice is ever cloned by this test. Run with
/// <c>REELBOLT_IT_FISH_SPEECH_ENDPOINT=http://localhost:8180</c> and
/// <c>REELBOLT_IT_WHISPER_ENDPOINT=http://localhost:9002/v1</c> (optionally
/// <c>REELBOLT_IT_WHISPER_MODEL</c>, default <c>Systran/faster-whisper-small</c>); skipped otherwise.
/// </para>
/// </summary>
public class FishSpeechSelfHostedCloningLiveTests
{
    private const string FishEndpointVar = "REELBOLT_IT_FISH_SPEECH_ENDPOINT";
    private const string WhisperEndpointVar = "REELBOLT_IT_WHISPER_ENDPOINT";
    private const string WhisperModelVar = "REELBOLT_IT_WHISPER_MODEL";

    public sealed class LiveFactAttribute : FactAttribute
    {
        public LiveFactAttribute()
        {
            string[] missing = new[] { FishEndpointVar, WhisperEndpointVar }
                .Where(v => string.IsNullOrWhiteSpace(Environment.GetEnvironmentVariable(v)))
                .ToArray();
            if (missing.Length > 0)
                Skip = "Requires a real self-hosted fish-speech server and transcription server. Missing: " + string.Join(", ", missing);
        }
    }

    private sealed class Owner(Guid id) : ICurrentUser
    {
        public Guid UserId { get; } = id;
        public string Email => "owner@example.com";
        public bool IsAuthenticated => true;
        public bool IsPlatformAdmin => false;
        public System.Guid? OrganizationId => ReelBolt.WorkflowEngine.Tests.TestTenancy.OrgOf(UserId);
        public ReelBolt.Shared.Tenancy.OrganizationRole? OrgRole => ReelBolt.Shared.Tenancy.OrganizationRole.Member;
    }

    [LiveFact]
    public async Task Clone_a_synthetic_voice_speak_with_it_and_delete_it()
    {
        string fishEndpoint = Environment.GetEnvironmentVariable(FishEndpointVar)!;
        string whisperEndpoint = Environment.GetEnvironmentVariable(WhisperEndpointVar)!;
        string whisperModel = Environment.GetEnvironmentVariable(WhisperModelVar) is { Length: > 0 } m ? m : "Systran/faster-whisper-small";

        var speechProvider = new ResolvedSpeechSynthesisProvider(Guid.NewGuid(), "it-local-fish", InferenceProviderKind.FishAudio, fishEndpoint, "s2-pro", "", 600);
        var asrProvider = new ResolvedTranscriptionProvider(Guid.NewGuid(), "it-whisper", InferenceProviderKind.OpenAICompatible, whisperEndpoint, whisperModel, "", 300);
        var speechFactory = new SpeechSynthesisClientFactory();
        ISpeechSynthesisClient speech = speechFactory.Get(speechProvider);

        // 1. A synthetic reference: the server's default voice (no reference_id) reading a sentence.
        const string referenceSentence = "This reference recording was generated by a speech synthesizer for an automated test.";
        byte[] referenceWav;
        await using (Stream s = (await speech.SynthesizeAsync(new SpeechRequest(referenceSentence, null, null), CancellationToken.None)).Wav)
        {
            using var ms = new MemoryStream();
            await s.CopyToAsync(ms);
            referenceWav = ms.ToArray();
        }
        FishAudioSpeechSynthesisClient.IsWav(referenceWav).Should().BeTrue();
        string? outPath = Environment.GetEnvironmentVariable("REELBOLT_IT_FISH_SPEECH_OUT");
        if (!string.IsNullOrWhiteSpace(outPath))
            await File.WriteAllBytesAsync(Path.Combine(outPath, "reference.wav"), referenceWav);

        // 2. The real controller, with only the database and the object store faked.
        var db = new InferenceApiDbContext(new DbContextOptionsBuilder<InferenceApiDbContext>()
            .UseInMemoryDatabase(Guid.NewGuid().ToString()).Options);
        var ownerId = Guid.NewGuid();
        var project = new Project { Id = Guid.NewGuid(), Name = "IT", OwnerId = ownerId, OrganizationId = TestTenancy.OrgOf(ownerId) };
        var file = new ProjectFile
        {
            Id = Guid.NewGuid(),
            ProjectId = project.Id,
            OriginalFileName = "synthetic-reference.wav",
            MimeType = "audio/wav",
            StorageKey = $"projects/{project.Id}/userFiles/synthetic-reference.wav",
            SizeBytes = referenceWav.Length,
            Category = "userFiles"
        };
        db.Projects.Add(project);
        db.ProjectFiles.Add(file);
        db.AddFlat(new ModelCapabilityView
        {
            Id = speechProvider.ProviderId!.Value,
            Name = speechProvider.Name,
            Kind = InferenceProviderKind.FishAudio,
            Capability = InferenceProviderCapability.SpeechSynthesis,
            Endpoint = fishEndpoint,
            ModelName = "s2-pro"
        });
        await db.SaveChangesAsync();

        var storage = new Mock<IFileStorageService>();
        storage.Setup(s => s.DownloadAsync(project.Id, file.StorageKey, It.IsAny<CancellationToken>()))
            .ReturnsAsync(() => new MemoryStream(referenceWav));
        storage.Setup(s => s.DeleteAsync(It.IsAny<Guid>(), It.IsAny<string>(), It.IsAny<CancellationToken>())).Returns(Task.CompletedTask);
        var resolver = new Mock<IInferenceProviderResolver>();
        resolver.Setup(r => r.ResolveSpeechSynthesisAsync(It.IsAny<Guid?>(), It.IsAny<CancellationToken>())).ReturnsAsync(speechProvider);
        resolver.Setup(r => r.ResolveTranscriptionAsync(null, It.IsAny<CancellationToken>())).ReturnsAsync(asrProvider);

        var controller = new ProjectVoicesController(db, new Owner(ownerId), TestTenancy.Access(db, new Owner(ownerId)), storage.Object, resolver.Object, speechFactory,
            new TranscriptionClientFactory(), NullLogger<ProjectVoicesController>.Instance);

        // 3. Clone, with the verbatim consent attestation (unchanged rules).
        ActionResult<ProjectVoiceResponse> cloned = await controller.Clone(project.Id, new CloneVoiceRequest(
            Name: "Synthetic test voice",
            ReferenceProjectFileIds: [file.Id],
            ConsentStatement: ProjectVoicesController.RequiredConsentStatement,
            ConsentSubjectName: "Synthetic voice (fish-speech default)",
            InferenceProviderId: speechProvider.ProviderId,
            RetentionDays: 1), CancellationToken.None);
        var voice = cloned.Result.Should().BeOfType<CreatedAtActionResult>().Subject.Value.Should().BeOfType<ProjectVoiceResponse>().Subject;
        voice.RemoteVoiceId.Should().StartWith(FishAudioSpeechSynthesisClient.SelfHostedReferenceIdPrefix);
        voice.Selectable.Should().BeTrue();

        using var http = new HttpClient { BaseAddress = new Uri(fishEndpoint.TrimEnd('/') + "/") };
        http.DefaultRequestHeaders.Accept.ParseAdd("application/json");
        string listed = await http.GetStringAsync("v1/references/list");
        JsonDocument.Parse(listed).RootElement.GetProperty("reference_ids").EnumerateArray()
            .Select(e => e.GetString()).Should().Contain(voice.RemoteVoiceId);

        // 4. Speak a line with the cloned voice (exactly what a Voiceover step sends). The delete in
        // the finally block runs whatever happens here, so a failed run leaves nothing behind.
        try
        {
            SynthesizedSpeech spoken = await speech.SynthesizeAsync(
                new SpeechRequest("Hello from the cloned test voice.", voice.RemoteVoiceId, null), CancellationToken.None);
            await using (spoken.Wav)
            {
                using var ms = new MemoryStream();
                await spoken.Wav.CopyToAsync(ms);
                FishAudioSpeechSynthesisClient.IsWav(ms.ToArray()).Should().BeTrue();
                ms.Length.Should().BeGreaterThan(44_100, "at least half a second of 44.1 kHz audio");
                if (!string.IsNullOrWhiteSpace(outPath))
                    await File.WriteAllBytesAsync(Path.Combine(outPath, "cloned-line.wav"), ms.ToArray());
            }
        }
        finally
        {
            // 5. Delete: the server-side reference, the recording and the row.
            var deleted = (await controller.Delete(project.Id, voice.Id, CancellationToken.None)).Result
                .Should().BeOfType<OkObjectResult>().Subject.Value.Should().BeOfType<DeleteVoiceResponse>().Subject;
            deleted.RemoteModelDeleted.Should().BeTrue();
            deleted.ReferenceFilesDeleted.Should().Be(1);
            string after = await http.GetStringAsync("v1/references/list");
            JsonDocument.Parse(after).RootElement.GetProperty("reference_ids").EnumerateArray()
                .Select(e => e.GetString()).Should().NotContain(voice.RemoteVoiceId);
        }
    }
}
