using System;
using System.Collections.Generic;
using System.Threading.Tasks;
using AwesomeAssertions;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Infrastructure;
using Microsoft.EntityFrameworkCore.Migrations;
using Npgsql;
using NpgsqlTypes;
using ReelBolt.Inference.Api.Data;
using ReelBolt.WorkflowEngine.Tests.Infrastructure;
using Xunit;

namespace ReelBolt.WorkflowEngine.Tests.Data;

/// <summary>
/// product-events-funnel T-001: the <c>AddProductEvents</c> migration against a real PostgreSQL. It
/// migrates a database of its own and drops it afterwards, and proves what the entity and the migration
/// declare: the six columns and their exact types and nullability, the identity primary key, the two
/// named <c>CHECK</c> constraints that are the schema's statement of the funnel's honesty, and the three
/// indexes the funnel query reads.
/// <para>
/// Follows <see cref="BillingPaymentsSchemaTests"/>: a per-test database,
/// <see cref="PostgresTestEnvironment"/>, and <c>DROP DATABASE ... WITH (FORCE)</c> in <c>finally</c>.
/// The migration's guarded <c>powerbi_ro</c> grant is a no-op here (the role does not exist in this
/// database), which reaching the assertions below proves: the migration applied.
/// </para>
/// </summary>
[Collection("Postgres")]
[Trait("Category", "Postgres")]
public class ProductEventsSchemaTests
{
    [PostgresFact]
    public async Task The_product_events_migration_creates_the_table_its_checks_and_its_indexes()
    {
        string baseConnection = PostgresTestEnvironment.BaseConnectionString()!;
        string dbName = "reelbolt_product_events_" + Guid.NewGuid().ToString("N")[..12];
        await using NpgsqlDataSource admin = PostgresTestEnvironment.CreateAdminDataSource(baseConnection);
        await using (NpgsqlCommand create = admin.CreateCommand($"CREATE DATABASE {dbName}"))
        {
            await create.ExecuteNonQueryAsync();
        }

        NpgsqlConnectionStringBuilder csb = new(PostgresTestEnvironment.ForDatabase(baseConnection, dbName));
        try
        {
            // The migration applies to a fresh database. Its powerbi_ro grant is guarded, and the role
            // does not exist here, so the DO block runs the GRANT for nobody and the migration succeeds.
            await using (InferenceApiDbContext api = new(
                new DbContextOptionsBuilder<InferenceApiDbContext>().UseNpgsql(csb.ConnectionString).Options))
            {
                await api.GetService<IMigrator>().MigrateAsync();
            }

            await using NpgsqlConnection c = new(csb.ConnectionString);
            await c.OpenAsync();

            async Task<object?> Scalar(string sql)
            {
                await using NpgsqlCommand cmd = new(sql, c);
                return await cmd.ExecuteScalarAsync();
            }

            // character_maximum_length is an int, so the value is stringified rather than cast.
            async Task<string?> Column(string column, string property)
            {
                object? value = await Scalar(
                    "SELECT " + property + " FROM information_schema.columns "
                    + $"WHERE table_schema = 'public' AND table_name = 'product_events' AND column_name = '{column}'");
                return value is null or DBNull ? null : System.Convert.ToString(value, System.Globalization.CultureInfo.InvariantCulture);
            }

            // --- the six columns, exactly as the entity and the migration declare them -----------------
            (await Column("id", "data_type")).Should().Be("bigint");
            (await Column("id", "is_nullable")).Should().Be("NO");
            (await Column("id", "is_identity")).Should().Be("YES",
                "the surrogate key is GENERATED BY DEFAULT AS IDENTITY");
            (await Column("id", "identity_generation")).Should().Be("BY DEFAULT");

            (await Column("user_id", "data_type")).Should().Be("uuid");
            (await Column("user_id", "is_nullable")).Should().Be("YES",
                "a payment belongs to an organization and may have no person");

            (await Column("organization_id", "data_type")).Should().Be("uuid");
            (await Column("organization_id", "is_nullable")).Should().Be("YES",
                "a client event belongs to a person and may have no organization");

            (await Column("event", "data_type")).Should().Be("character varying");
            (await Column("event", "character_maximum_length")).Should().Be("64");
            (await Column("event", "is_nullable")).Should().Be("NO");

            (await Column("occurred_at", "data_type")).Should().Be("timestamp with time zone");
            (await Column("occurred_at", "is_nullable")).Should().Be("NO");

            (await Column("source", "data_type")).Should().Be("character varying");
            (await Column("source", "character_maximum_length")).Should().Be("16");
            (await Column("source", "is_nullable")).Should().Be("NO");

            // --- the primary key is id -----------------------------------------------------------------
            (await Scalar(
                "SELECT a.attname FROM pg_index i JOIN pg_attribute a ON a.attrelid = i.indrelid AND a.attnum = ANY(i.indkey) "
                + "JOIN pg_class t ON t.oid = i.indrelid JOIN pg_namespace n ON n.oid = t.relnamespace "
                + "WHERE n.nspname = 'public' AND t.relname = 'product_events' AND i.indisprimary"))
                .Should().Be("id");

            // --- the two CHECK constraints are present by name -----------------------------------------
            async Task<string?> CheckExpression(string name) => (string?)await Scalar(
                "SELECT pg_get_constraintdef(oid) FROM pg_constraint "
                + $"WHERE conname = '{name}' AND conrelid = 'public.product_events'::regclass AND contype = 'c'");

            string? subjectCheck = await CheckExpression("ck_product_events_subject");
            subjectCheck.Should().NotBeNull("the subject CHECK must be present by name");
            subjectCheck.Should().Contain("user_id").And.Contain("organization_id");

            string? sourceCheck = await CheckExpression("ck_product_events_source");
            sourceCheck.Should().NotBeNull("the source CHECK must be present by name");
            sourceCheck.Should().Contain("server").And.Contain("client").And.Contain("consent");

            // --- the three indexes exist, on the columns the funnel query reads -------------------------
            async Task<List<string>> IndexColumns(string indexName)
            {
                List<string> columns = new();
                await using NpgsqlCommand cmd = new(
                    "SELECT a.attname FROM pg_index i "
                    + "JOIN pg_class ic ON ic.oid = i.indexrelid "
                    + "JOIN pg_attribute a ON a.attrelid = i.indrelid AND a.attnum = ANY(i.indkey) "
                    + "JOIN pg_namespace n ON n.oid = ic.relnamespace "
                    + $"WHERE n.nspname = 'public' AND ic.relname = '{indexName}' ORDER BY a.attnum", c);
                await using NpgsqlDataReader reader = await cmd.ExecuteReaderAsync();
                while (await reader.ReadAsync())
                {
                    columns.Add(reader.GetString(0));
                }

                return columns;
            }

            (await IndexColumns("ix_product_events_user_id_occurred_at")).Should().Equal("user_id", "occurred_at");
            (await IndexColumns("ix_product_events_event_occurred_at")).Should().Equal("event", "occurred_at");
            (await IndexColumns("ix_product_events_organization_id")).Should().Equal("organization_id");

            // --- the vocabulary and the subject rule are enforced, not merely declared ------------------
            async Task InsertAsync(string source, Guid? userId, Guid? orgId)
            {
                await using NpgsqlCommand insert = new(
                    "INSERT INTO product_events (user_id, organization_id, event, occurred_at, source) "
                    + "VALUES (@user_id, @organization_id, 'alpha.signup', now(), @source)", c);
                insert.Parameters.AddWithValue("source", source);
                // Explicit Uuid types: a bare DBNull is inferred as text and would fail the insert with
                // 42804 against the uuid columns, masking the CHECK the test is about.
                insert.Parameters.Add(new NpgsqlParameter("user_id", NpgsqlDbType.Uuid)
                {
                    Value = userId is null ? DBNull.Value : userId.Value
                });
                insert.Parameters.Add(new NpgsqlParameter("organization_id", NpgsqlDbType.Uuid)
                {
                    Value = orgId is null ? DBNull.Value : orgId.Value
                });
                await insert.ExecuteNonQueryAsync();
            }

            // A source outside the closed set is refused by the database (23514 = check_violation).
            Func<Task> bogusSource = () => InsertAsync("bogus", Guid.NewGuid(), null);
            (await bogusSource.Should().ThrowAsync<PostgresException>()).Which.SqlState.Should().Be("23514",
                "a fifth source value needs a migration on purpose, not a typo in an emitter");

            // A row that names neither a person nor an organization is refused.
            Func<Task> noSubject = () => InsertAsync("server", null, null);
            (await noSubject.Should().ThrowAsync<PostgresException>()).Which.SqlState.Should().Be("23514",
                "a product event must name at least one of user_id / organization_id");

            // The legal shapes are accepted: person-only, organization-only, and both.
            await InsertAsync("client", Guid.NewGuid(), null);
            await InsertAsync("server", null, Guid.NewGuid());
            await InsertAsync("consent", Guid.NewGuid(), Guid.NewGuid());

            (await Scalar("SELECT count(*) FROM product_events")).Should().Be(3L);

            // The surrogate key is server-assigned (identity), so a writer never supplies it.
            (await Scalar("SELECT count(DISTINCT id) FROM product_events")).Should().Be(3L);
        }
        finally
        {
            NpgsqlConnection.ClearAllPools();
            await using NpgsqlDataSource dropAdmin = PostgresTestEnvironment.CreateAdminDataSource(baseConnection);
            await using NpgsqlCommand drop = dropAdmin.CreateCommand($"DROP DATABASE IF EXISTS {dbName} WITH (FORCE)");
            await drop.ExecuteNonQueryAsync();
        }
    }

    /// <summary>
    /// The positive half of the migration's guarded grant: when <c>powerbi_ro</c> exists, the creation
    /// migration grants it <c>SELECT</c> on the new table — the path that lets an already-deployed
    /// database converge without an operator re-running the script. The other half (a fresh database
    /// with no role) is the test above, which applies the same migration without the role and succeeds.
    /// <para>
    /// The role is created if absent and deliberately <b>not</b> dropped: roles are cluster-wide and the
    /// suite already leaves <c>powerbi_ro</c> behind (<c>PowerBiReadOnlyRolePostgresTests</c> creates it
    /// via the operator script and does not remove it), and a <c>DROP ROLE</c> would fail while any
    /// sibling database still holds a grant to it. Postgres-gated tests run in one collection, so this
    /// does not race.
    /// </para>
    /// </summary>
    [PostgresFact]
    public async Task The_creation_migration_grants_select_to_powerbi_ro_when_the_role_exists()
    {
        string baseConnection = PostgresTestEnvironment.BaseConnectionString()!;
        string dbName = "reelbolt_product_events_grant_" + Guid.NewGuid().ToString("N")[..12];
        await using NpgsqlDataSource admin = PostgresTestEnvironment.CreateAdminDataSource(baseConnection);

        // Ensure the role exists, exactly as the operator script would (CREATE ROLE ... LOGIN, guarded
        // by IF NOT EXISTS). CREATE ROLE needs the superuser this admin source connects as.
        await using (NpgsqlCommand role = admin.CreateCommand(
            "DO $$ BEGIN IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'powerbi_ro') THEN "
            + "CREATE ROLE powerbi_ro LOGIN; END IF; END $$;"))
        {
            await role.ExecuteNonQueryAsync();
        }

        await using (NpgsqlCommand create = admin.CreateCommand($"CREATE DATABASE {dbName}"))
        {
            await create.ExecuteNonQueryAsync();
        }

        NpgsqlConnectionStringBuilder csb = new(PostgresTestEnvironment.ForDatabase(baseConnection, dbName));
        try
        {
            await using (InferenceApiDbContext api = new(
                new DbContextOptionsBuilder<InferenceApiDbContext>().UseNpgsql(csb.ConnectionString).Options))
            {
                await api.GetService<IMigrator>().MigrateAsync();
            }

            await using NpgsqlConnection c = new(csb.ConnectionString);
            await c.OpenAsync();

            async Task<object?> Scalar(string sql)
            {
                await using NpgsqlCommand cmd = new(sql, c);
                return await cmd.ExecuteScalarAsync();
            }

            (await Scalar("SELECT has_table_privilege('powerbi_ro', 'public.product_events', 'SELECT')"))
                .Should().Be(true, "the creation migration grants powerbi_ro SELECT when the role exists");
            (await Scalar("SELECT has_table_privilege('powerbi_ro', 'public.product_events', 'UPDATE')"))
                .Should().Be(false, "the grant is read-only: no write privilege comes with it");
        }
        finally
        {
            // Drop on a data source created *after* the pools are cleared, the same shape as
            // BillingPaymentsSchemaTests' teardown.
            NpgsqlConnection.ClearAllPools();
            await using NpgsqlDataSource dropAdmin = PostgresTestEnvironment.CreateAdminDataSource(baseConnection);
            await using NpgsqlCommand drop = dropAdmin.CreateCommand($"DROP DATABASE IF EXISTS {dbName} WITH (FORCE)");
            await drop.ExecuteNonQueryAsync();
        }
    }
}
