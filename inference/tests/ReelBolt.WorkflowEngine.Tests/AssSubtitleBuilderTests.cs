    [Fact]
    public void Subtitle_on_a_landscape_canvas_is_a_boxed_lower_third_in_Inter_at_the_automatic_size()
    {
        CaptionLayout layout = CaptionLayout.Resolve(1920, 1080, CaptionStyle.Subtitle, 4, CaptionPosition.Auto);
        ResolvedCaptionCue[] cues =
        [
            new("vo0", 0, "deploys go from forty", 2.0, 3.2),
            new("vo0", 1, "minutes to four", 3.2, 4.4)
        ];

        string script = AssSubtitleBuilder.Build(
            cues, CaptionStyle.Subtitle, layout, CaptionFontCatalog.Get(CaptionFont.Inter), White, Box, Yellow);

        script.Should().Be(
            "[Script Info]\n" +
            "; Burned captions generated by ReelBolt (docs/voiceover.md \"Captions\")\n" +
            "ScriptType: v4.00+\n" +
            "PlayResX: 1920\n" +
            "PlayResY: 1080\n" +
            "WrapStyle: 0\n" +
            "ScaledBorderAndShadow: yes\n" +
            "YCbCr Matrix: None\n" +
            "\n" +
            "[V4+ Styles]\n" +
            ScriptHeaderFormat + "\n" +
            // 5.5% of 1080 = 59px; BorderStyle 3 = opaque box filled with the OutlineColour
            // (black at 60% opacity = alpha 0x66), padded by 22% of the size.
            "Style: Caption,Inter,59,&H00FFFFFF,&H00FFFFFF,&H66000000,&H66000000,-1,0,0,0,100,100,0,0,3,13,0,2,154,154,86,1\n" +
            "\n" +
            "[Events]\n" +
            EventFormat + "\n" +
            "Dialogue: 0,0:00:02.00,0:00:03.20,Caption,,0,0,0,,deploys go from forty\n" +
            "Dialogue: 0,0:00:03.20,0:00:04.40,Caption,,0,0,0,,minutes to four\n");
    }

    [Fact]
    public void A_cue_moved_off_a_busy_bottom_is_drawn_top_centre_at_the_top_margin_and_the_rest_stay_put()
    {
        CaptionLayout layout = CaptionLayout.Resolve(1920, 1080, CaptionStyle.Subtitle, 0, CaptionPosition.Auto);
        string script = AssSubtitleBuilder.Build(
            [new ResolvedCaptionCue("vo0", 0, "On the timeline", 0.0, 1.5, AtTop: true),
             new ResolvedCaptionCue("vo1", 1, "Back at the bottom", 1.5, 3.0)],
            CaptionStyle.Subtitle, layout, CaptionFontCatalog.Get(CaptionFont.Inter), White, Box, Yellow);

        string[] events = script.Split('\n').Where(l => l.StartsWith("Dialogue:", StringComparison.Ordinal)).ToArray();
        events[0].Should().Contain($",0,0,{layout.TopMarginV},,{{\\an8}}On the timeline");
        events[1].Should().Contain(",0,0,0,,Back at the bottom");
        layout.TopMarginV.Should().Be(86, "8% of 1080 — the same title-safe margin the Top position uses");
    }

    [Fact]
    public void Karaoke_folds_the_per_word_cues_back_into_one_event_per_chunk_with_k_durations_from_the_measured_word_starts()
    {
        // Exactly what CaptionCueBuilder emits for Karaoke: one cue per word, each carrying the
        // chunk text and the prefix spoken so far, ending where the next word begins.
        ResolvedCaptionCue[] cues =
        [
            new("vo0", 0, "deploys go from", 2.0, 2.4, "deploys"),
            new("vo0", 1, "deploys go from", 2.4, 2.6, "deploys go"),
            new("vo0", 2, "deploys go from", 2.6, 2.8, "deploys go from"),
            new("vo0", 3, "forty minutes", 2.8, 3.2, "forty"),
            new("vo0", 4, "forty minutes", 3.2, 3.75, "forty minutes")
        ];
        CaptionLayout layout = CaptionLayout.Resolve(1080, 1920, CaptionStyle.Karaoke, 0, CaptionPosition.Auto);

        string script = AssSubtitleBuilder.Build(
            cues, CaptionStyle.Karaoke, layout, CaptionFontCatalog.Get(CaptionFont.Montserrat), White, Box, Yellow);

        // Portrait: 8% of the 1080 short side = 86px, 20% bottom margin clear of the platform UI.
        // Karaoke's PrimaryColour is the HIGHLIGHT (a word flips to it when its \k begins) and the
        // SecondaryColour is the not-yet-spoken text colour.
        script.Should().Contain(
            "Style: Caption,Montserrat,86,&H0000FFFF,&H00FFFFFF,&H66000000,&H66000000,-1,0,0,0,100,100,0,0,3,19,0,2,86,86,384,1\n");
        script.Should().EndWith(
            EventFormat + "\n" +
            "Dialogue: 0,0:00:02.00,0:00:02.80,Caption,,0,0,0,,{\\k40}deploys {\\k20}go {\\k20}from\n" +
            "Dialogue: 0,0:00:02.80,0:00:03.75,Caption,,0,0,0,,{\\k40}forty {\\k55}minutes\n");
    }

    [Fact]
    public void Karaoke_a_chunk_repeated_back_to_back_still_starts_a_new_event_when_the_prefix_restarts()
    {
        ResolvedCaptionCue[] cues =
        [
            new("vo0", 0, "go go", 0.0, 0.3, "go"),
            new("vo0", 1, "go go", 0.3, 0.6, "go go"),
            new("vo0", 2, "go go", 0.6, 0.9, "go"),
            new("vo0", 3, "go go", 0.9, 1.2, "go go")
