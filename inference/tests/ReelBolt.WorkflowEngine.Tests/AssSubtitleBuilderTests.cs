    [FfmpegLibassFact]
    public void A_real_ffmpeg_burns_the_generated_script_with_the_bundled_font()
    {
        string dir = Path.Combine(Path.GetTempPath(), "ass-smoke-" + Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(dir);
        try
        {
            const int W = 640, H = 360;
            CaptionLayout layout = CaptionLayout.Resolve(W, H, CaptionStyle.Subtitle, 0, CaptionPosition.Auto);
            string script = AssSubtitleBuilder.Build(
                [new ResolvedCaptionCue("vo0", 0, "Don't {\\b1} wait", 0, 2)], CaptionStyle.Subtitle, layout,
                CaptionFontCatalog.Get(CaptionFont.Inter), White, Parse("black@1"), Yellow);
            string assPath = Path.Combine(dir, AssSubtitleBuilder.ScriptFileName);
            File.WriteAllText(assPath, script);
            string graph = Path.Combine(dir, "graph.txt");
            File.WriteAllText(graph, CaptionFilterBuilder.BuildAssFilter("[0:v]", assPath, RepoFontsDir()));
            string output = Path.Combine(dir, "out.rgb");

            (int exit, string err) = Run(
                "-v", "verbose", "-y", "-f", "lavfi", "-i", $"color=c=gray:size={W}x{H}:rate=10:duration=0.1",
                "-filter_complex_script", graph, "-map", "[vout]", "-frames:v", "1", "-f", "rawvideo", "-pix_fmt", "rgb24", output);
            exit.Should().Be(0, err);
            err.Should().Contain("-> Inter-Bold", "libass must pick the bundled face, not a fontconfig substitute");

            byte[] rgb = File.ReadAllBytes(output);
            int Brightness(int x, int y) => rgb[(y * W + x) * 3];
            // The opaque black box sits in the lower third, centred; the top of the frame is untouched.
            int lowerThirdDark = Enumerable.Range(0, W).Count(x => Brightness(x, H - 40) < 40);
            lowerThirdDark.Should().BeGreaterThan(50, "the boxed caption is drawn above the 8% bottom margin");
            Brightness(W / 2, 20).Should().BeInRange(120, 136, "nothing is drawn at the top");
        }
        finally
        {
            Directory.Delete(dir, recursive: true);
        }
    }

    private static (int Exit, string Err) Run(params string[] args)
    {
        var psi = new ProcessStartInfo("ffmpeg") { RedirectStandardError = true, RedirectStandardOutput = true };
        foreach (string a in args)
            psi.ArgumentList.Add(a);
        using Process p = Process.Start(psi)!;
        string err = p.StandardError.ReadToEnd();
        p.StandardOutput.ReadToEnd();
        p.WaitForExit();
        return (p.ExitCode, err);
    }

    internal static string RepoFontsDir([System.Runtime.CompilerServices.CallerFilePath] string sourceFile = "")
    {
        // From this source file's own location, not the build output — test artifacts may be
        // built outside the repository.
        DirectoryInfo? dir = new FileInfo(sourceFile).Directory;
        while (dir is not null && !Directory.Exists(Path.Combine(dir.FullName, "fonts", "captions")))
            dir = dir.Parent;
        dir.Should().NotBeNull("the test runs inside the repository, under inference/");
        return Path.Combine(dir!.FullName, "fonts", "captions");
    }

    private static CaptionColor Parse(string value)
    {
        CaptionColor.TryParse(value, out CaptionColor color).Should().BeTrue();
        return color;
    }
