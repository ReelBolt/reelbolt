    [Fact]
    public void Auto_font_follows_the_style_and_a_missing_font_file_falls_back_to_DejaVu_with_a_reason()
    {
        string dir = Path.Combine(Path.GetTempPath(), "caption-fonts-" + Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(dir);
        try
        {
            File.WriteAllBytes(Path.Combine(dir, "Anton-Regular.ttf"), [0]);

            CaptionFontCatalog.Resolve(CaptionFont.Auto, CaptionStyle.Punch, dir)
                .Should().Be((CaptionFontCatalog.Get(CaptionFont.Anton), (string?)null));

            (CaptionFontFace face, string? reason) = CaptionFontCatalog.Resolve(CaptionFont.Auto, CaptionStyle.Subtitle, dir);
            face.Family.Should().Be("DejaVu Sans", "Inter-Bold.ttf is not in this directory");
            reason.Should().Be(CaptionFontCatalog.FontNotInstalledReason);

            CaptionFontCatalog.Resolve(CaptionFont.Montserrat, CaptionStyle.Subtitle, null).Reason().Should().Be("font_not_installed");
            CaptionFontCatalog.Resolve(CaptionFont.DejaVuSans, CaptionStyle.Punch, null)
                .Should().Be((CaptionFontCatalog.Get(CaptionFont.DejaVuSans), (string?)null), "DejaVu Sans is the image's system font");
        }
        finally
        {
            Directory.Delete(dir, recursive: true);
        }
    }

