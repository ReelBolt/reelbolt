/// <summary>Skips at discovery time unless an <c>ffmpeg</c> on PATH has the libass <c>ass</c> filter.</summary>
public sealed class FfmpegLibassFactAttribute : FactAttribute
{
    public FfmpegLibassFactAttribute()
    {
        try
        {
            var psi = new ProcessStartInfo("ffmpeg", "-hide_banner -filters") { RedirectStandardOutput = true, RedirectStandardError = true };
            using Process p = Process.Start(psi)!;
            string stdout = p.StandardOutput.ReadToEnd();
            p.StandardError.ReadToEnd();
            p.WaitForExit();
            if (p.ExitCode != 0 || !System.Text.RegularExpressions.Regex.IsMatch(stdout, @"(?<![\w-])ass(?![\w-])"))
                Skip = "Requires an ffmpeg with the libass ass filter.";
        }
        catch (Exception)
        {
            Skip = "Requires an ffmpeg binary on PATH.";
        }
    }
