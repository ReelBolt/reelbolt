    [Fact]
    public void Spoken_text_can_never_open_an_override_block_form_an_escape_or_start_a_new_script_line()
    {
        AssSubtitleBuilder.EscapeText("a{\\b1}c").Should().Be("a(\\\u2060b1)c");
        AssSubtitleBuilder.EscapeText("x\\Ny\\nz\\hw").Should().Be("x\\\u2060Ny\\\u2060nz\\\u2060hw");
        AssSubtitleBuilder.EscapeText("one\nDialogue: 0,0:00:00.00,9:00:00.00,Caption,,0,0,0,,owned")
            .Should().Be("one Dialogue: 0,0:00:00.00,9:00:00.00,Caption,,0,0,0,,owned", "a newline would end the event line");
        AssSubtitleBuilder.EscapeText("tab\there\r\u2028").Should().Be("tab here  ");
        AssSubtitleBuilder.EscapeText("don't, ok: fine; 100%").Should().Be("don't, ok: fine; 100%", "plain punctuation is inert in ASS text");

        string script = AssSubtitleBuilder.Build(
            [new ResolvedCaptionCue("vo0", 0, "{\\pos(0,0)}hi\nStyle: X", 0, 1)], CaptionStyle.Subtitle,
            CaptionLayout.Resolve(1920, 1080, CaptionStyle.Subtitle, 0, CaptionPosition.Auto),
            CaptionFontCatalog.Get(CaptionFont.Inter), White, Box, Yellow);
        script.Split('\n').Should().ContainSingle(l => l.StartsWith("Style:", StringComparison.Ordinal));
        script.Should().Contain(",,(\\\u2060pos(0,0))hi Style: X\n");
    }

    [Fact]
    public void The_caption_sanitizer_keeps_narration_punctuation_and_drops_override_syntax()
    {
        CaptionTextSanitizer.Sanitize("Don't wait, ship: now; “really”…", 400).Should().Be("Don't wait, ship: now; “really”…");
        CaptionTextSanitizer.Sanitize("a{\\b1}b\\Nc %d", 400).Should().Be("ab1bNc d");
        CaptionTextSanitizer.Sanitize("  \n ", 400).Should().BeEmpty();
    }

