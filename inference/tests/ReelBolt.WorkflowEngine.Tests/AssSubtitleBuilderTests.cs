        var events = AssSubtitleBuilder.ToEvents(cues, CaptionStyle.Karaoke).ToList();

        events.Should().HaveCount(2);
        events[0].Text.Should().Be("{\\k30}go {\\k30}go");
        events[1].StartSec.Should().Be(0.6);
    }

    [Fact]
    public void Punch_is_big_centred_and_outlined_with_no_box_and_a_too_long_word_is_shrunk_to_the_safe_width()
    {
        CaptionLayout layout = CaptionLayout.Resolve(1080, 1920, CaptionStyle.Punch, 4, CaptionPosition.Auto);
        ResolvedCaptionCue[] cues =
        [
            new("vo0", 0, "Ship", 1.0, 1.4),
            new("vo0", 1, "internationalization", 1.4, 2.2)
        ];

        string script = AssSubtitleBuilder.Build(
            cues, CaptionStyle.Punch, layout, CaptionFontCatalog.Get(CaptionFont.Anton), White, Box, Yellow);

        // 13% of 1080 = 140px, centred (alignment 5), heavy outline + soft shadow, box colour
        // ignored, Anton never synthetically emboldened.
        script.Should().Contain(
            "Style: Caption,Anton,140,&H00FFFFFF,&H00FFFFFF,&H00000000,&H80000000,0,0,0,0,100,100,0,0,1,13,7,5,86,86,0,1\n");
        script.Should().Contain("Dialogue: 0,0:00:01.00,0:00:01.40,Caption,,0,0,0,,Ship\n");
        // 20 chars x 0.5em x 140px = 1400px > the 882px safe width (1080 - 2x86 margins - 2x13
        // outline): shrunk to floor(140 x 882 / 1400) = 88px for this cue only.
        script.Should().Contain("Dialogue: 0,0:00:01.40,0:00:02.20,Caption,,0,0,0,,{\\fs88}internationalization\n");
    }

