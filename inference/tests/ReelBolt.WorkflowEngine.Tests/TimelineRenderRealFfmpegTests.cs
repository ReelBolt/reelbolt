    [FfmpegFact]
    public async Task R10_4_the_preview_preset_renders_540p_h264_aac_in_the_timelines_aspect_within_three_seconds()
    {
        AssetRef source = Source("preview-src", "testsrc=s=320x180:r=30", 2, audio: "sine=f=440:sample_rate=48000");
        foreach ((int w, int h, int expectW, int expectH) in new[] { (1920, 1080, 960, 540), (1080, 1920, 540, 960), (1080, 1080, 540, 540) })
        {
            EditTimelineSettings settings = new(w, h, new Rational(30, 1), 48000, new Rational(1, 1), AspectPolicy.Fit, 0);
            EditTimeline doc = new(Guid.NewGuid(), ProjectId, "doc", settings, [Video(Clip(source, 0, 60)), Audio(Clip(source, 0, 60))], [], null, null);
            FfmpegVideoToolRunner runner = RealRunner();
            string scratch = Path.Combine(_work, "scratch-" + Guid.NewGuid().ToString("N"));
            string output = Path.Combine(_work, "preview-" + Guid.NewGuid().ToString("N") + ".mp4");
            TimelineRenderEnvironment env = new(runner, scratch, "/fonts/missing.ttf", TimeSpan.FromMinutes(2), 2, NullRegionCache.Instance, ProjectId);
            TimelineRenderStepConfig config = new(doc.Id, Preset: TimelineRenderPreset.Preview, Range: new TimelineRenderRange(0, 60), RegisterProjectFile: false);

            await new TimelineRenderer(NullLogger.Instance).RenderAsync(doc, config, _assets, output, env, CancellationToken.None);

            string json = Run("ffprobe", ["-v", "error", "-show_entries", "format=duration:stream=codec_type,codec_name,width,height,pix_fmt", "-of", "json", output]);
            using JsonDocument probe = JsonDocument.Parse(json);
            double duration = double.Parse(probe.RootElement.GetProperty("format").GetProperty("duration").GetString()!, CultureInfo.InvariantCulture);
            duration.Should().BeLessThanOrEqualTo(3.1).And.BeApproximately(2.0, 0.1);
            JsonElement[] streams = probe.RootElement.GetProperty("streams").EnumerateArray().ToArray();
            streams.Select(x => x.GetProperty("codec_type").GetString()).Order().Should().Equal("audio", "video");
            JsonElement video = streams.Single(x => x.GetProperty("codec_type").GetString() == "video");
            video.GetProperty("width").GetInt32().Should().Be(expectW);
            video.GetProperty("height").GetInt32().Should().Be(expectH);
            video.GetProperty("codec_name").GetString().Should().Be("h264");
            video.GetProperty("pix_fmt").GetString().Should().Be("yuv420p");
            streams.Single(x => x.GetProperty("codec_type").GetString() == "audio").GetProperty("codec_name").GetString().Should().Be("aac");
        }
    }

    // ── fixtures ─────────────────────────────────────────────────────────────

    private static Keyframed<double> Ramp(long at) =>
        new(0, [new Keyframe<double>(at, -6, InterpKind.Linear), new Keyframe<double>(at + 5, 0, InterpKind.Linear)]);

    private MediaClip Clip(AssetRef asset, long recordIn, long recordOut, long sourceIn = 0, double rate = 1.0, Keyframed<double>? gain = null) =>
        new(Guid.NewGuid(), $"clip-{++_ids}", recordIn, recordOut, asset, sourceIn, rate, true, null, gain);

    private static MediaClip Depth(MediaClip clip, ClipTransform? transform = null) =>
        new(clip.Id, clip.Name, clip.RecordIn, clip.RecordOut, clip.AssetRef, clip.SourceIn, clip.PlaybackRate, clip.Enabled, clip.Provenance, clip.GainDb, transform);

    private Track Video(params Item[] items) =>
        new(Guid.NewGuid(), TrackKind.Video, $"V{++_ids}", null, 64, false, true, false, false, null, items);

    private Track Audio(params Item[] items) =>
        new(Guid.NewGuid(), TrackKind.Audio, $"A{++_ids}", null, 48, false, true, false, false, null, items);

    private static EditTimeline Doc(params Track[] tracks) =>
        new(Guid.NewGuid(), ProjectId, "doc", Settings, tracks, [], null, null);

    /// <summary>A generated source file (ffmpeg lavfi), registered as an asset with an honest probe.</summary>
    private AssetRef Source(string name, string video, double seconds, int width = 320, int height = 180, string? audio = null)
    {
        string path = Path.Combine(_work, $"{name}.mp4");
        List<string> args = ["-hide_banner", "-loglevel", "error", "-y", "-f", "lavfi", "-i", video];
        if (audio is not null) args.AddRange(["-f", "lavfi", "-i", audio]);
        args.AddRange(["-t", seconds.ToString(CultureInfo.InvariantCulture), "-pix_fmt", "yuv420p", "-c:v", "libx264", "-g", "15"]);
        if (audio is not null) args.AddRange(["-c:a", "aac", "-ac", "2"]);
        args.Add(path);
        Run("ffmpeg", args);

        AssetRef reference = new(AssetRefKind.ProjectFile, Guid.NewGuid(), null);
        _assets[reference] = new LocalAsset(path, $"{name}|{Guid.NewGuid():N}",
            new MediaProbeResult(seconds, 30, 1, width, height, "h264", audio is null ? null : "aac", audio is null ? null : 48000));
        return reference;
    }

    private static FfmpegVideoToolRunner RealRunner() =>
        new(Options.Create(new VideoEditingOptions { ScratchPath = Path.GetTempPath(), MaxConcurrentJobs = 2, CompileTimeoutSeconds = 120 }),
            NullLogger<FfmpegVideoToolRunner>.Instance);

    private async Task<(TimelineRenderResult Result, string Output, IVideoToolRunner Runner)> Render(EditTimeline doc, IVideoToolRunner? runner = null)
    {
        runner ??= RealRunner();
        string scratch = Path.Combine(_work, "scratch-" + Guid.NewGuid().ToString("N"));
        string output = Path.Combine(_work, "out-" + Guid.NewGuid().ToString("N") + ".mp4");
        TimelineRenderEnvironment env = new(runner, scratch, "/fonts/missing.ttf", TimeSpan.FromMinutes(2), 2, NullRegionCache.Instance, ProjectId);
        TimelineRenderStepConfig config = new(doc.Id, Preset: TimelineRenderPreset.Master);
        TimelineRenderResult result = await new TimelineRenderer(NullLogger.Instance).RenderAsync(doc, config, _assets, output, env, CancellationToken.None);
        return (result, output, runner);
    }

    private async Task<string> RenderOk(EditTimeline doc) => (await Render(doc)).Output;

    /// <summary>The delivery exists, lasts <paramref name="seconds"/> and carries one video and one audio stream.</summary>
    private static void AssertDeliveryFacts(string output, double seconds)
    {
        File.Exists(output).Should().BeTrue();
        string json = Run("ffprobe", ["-v", "error", "-show_entries", "format=duration:stream=codec_type", "-of", "json", output]);
        using JsonDocument probe = JsonDocument.Parse(json);
        double duration = double.Parse(probe.RootElement.GetProperty("format").GetProperty("duration").GetString()!, CultureInfo.InvariantCulture);
        duration.Should().BeApproximately(seconds, 0.1);
        probe.RootElement.GetProperty("streams").EnumerateArray().Select(s => s.GetProperty("codec_type").GetString()).Order()
            .Should().Equal("audio", "video");
    }

    /// <summary>One RGB pixel of the frame shown at <paramref name="atSec"/>.</summary>
    private static (int R, int G, int B) Pixel(string video, double atSec, int x, int y)
    {
        byte[] frame = RunBytes("ffmpeg", ["-hide_banner", "-loglevel", "error", "-ss", atSec.ToString("R", CultureInfo.InvariantCulture), "-i", video,
            "-frames:v", "1", "-f", "rawvideo", "-pix_fmt", "rgb24", "-"]);
        frame.Length.Should().Be(320 * 180 * 3);
        int i = (y * 320 + x) * 3;
        return (frame[i], frame[i + 1], frame[i + 2]);
    }

    /// <summary>RMS level (dBFS) of the delivery's sound over [at, at + length).</summary>
    private static double RmsDb(string video, double atSec, double lengthSec)
    {
        byte[] pcm = RunBytes("ffmpeg", ["-hide_banner", "-loglevel", "error", "-ss", atSec.ToString("R", CultureInfo.InvariantCulture), "-t", lengthSec.ToString("R", CultureInfo.InvariantCulture),
            "-i", video, "-vn", "-ac", "1", "-ar", "8000", "-f", "s16le", "-"]);
        double sum = 0;
        int n = pcm.Length / 2;
        for (int i = 0; i < n; i++)
        {
            double s = BitConverter.ToInt16(pcm, i * 2) / 32768.0;
            sum += s * s;
        }

        double rms = n == 0 ? 0 : Math.Sqrt(sum / n);
        return rms <= 0 ? -120 : 20 * Math.Log10(rms);
    }

    private static bool Near((int R, int G, int B) actual, (int R, int G, int B) expected) =>
        Math.Abs(actual.R - expected.R) <= 40 && Math.Abs(actual.G - expected.G) <= 40 && Math.Abs(actual.B - expected.B) <= 40;

    private static string Run(string tool, IEnumerable<string> args) => System.Text.Encoding.UTF8.GetString(RunBytes(tool, args));

    private static byte[] RunBytes(string tool, IEnumerable<string> args)
    {
        ProcessStartInfo info = new(tool) { RedirectStandardOutput = true, RedirectStandardError = true, UseShellExecute = false };
        foreach (string arg in args) info.ArgumentList.Add(arg);
        using Process process = Process.Start(info)!;
        using MemoryStream stdout = new();
        Task copy = process.StandardOutput.BaseStream.CopyToAsync(stdout);
        string stderr = process.StandardError.ReadToEnd();
        copy.Wait(60_000);
        process.WaitForExit(60_000);
        process.ExitCode.Should().Be(0, $"{tool} failed: {stderr}");
        return stdout.ToArray();
    }

    /// <summary>The real runner, counting every invocation.</summary>
    private sealed class CountingRunner(IVideoToolRunner inner) : IVideoToolRunner
    {
        private int _calls;

        public int Calls => _calls;

        private IVideoToolRunner Count()
        {
            Interlocked.Increment(ref _calls);
            return inner;
        }

        public Task<VideoToolResult> RunFfmpegAsync(IReadOnlyList<string> args, TimeSpan timeout, CancellationToken ct) => Count().RunFfmpegAsync(args, timeout, ct);
        public Task<VideoToolResult> RunFfmpegAsync(IReadOnlyList<string> args, TimeSpan timeout, CancellationToken ct, Action<string> onStdOutLine) => Count().RunFfmpegAsync(args, timeout, ct, onStdOutLine);
        public Task<VideoToolResult> RunFfprobeAsync(IReadOnlyList<string> args, TimeSpan timeout, CancellationToken ct) => Count().RunFfprobeAsync(args, timeout, ct);
        public Task<VideoToolResult> RunFfmpegAsync(IReadOnlyList<string> args, TimeSpan timeout, CancellationToken ct, VideoToolPriority priority) => Count().RunFfmpegAsync(args, timeout, ct, priority);
        public Task<VideoToolResult> RunFfmpegAsync(IReadOnlyList<string> args, TimeSpan timeout, CancellationToken ct, Action<string> onStdOutLine, VideoToolPriority priority) => Count().RunFfmpegAsync(args, timeout, ct, onStdOutLine, priority);
        public Task<VideoToolResult> RunFfprobeAsync(IReadOnlyList<string> args, TimeSpan timeout, CancellationToken ct, VideoToolPriority priority) => Count().RunFfprobeAsync(args, timeout, ct, priority);
        public Task<VideoToolResult> RunFfmpegAsync(IMediaWorkspace workspace, IReadOnlyList<string> args, TimeSpan timeout, CancellationToken ct) => Count().RunFfmpegAsync(workspace, args, timeout, ct);
        public Task<VideoToolResult> RunFfmpegAsync(IMediaWorkspace workspace, IReadOnlyList<string> args, TimeSpan timeout, CancellationToken ct, Action<string> onStdOutLine) => Count().RunFfmpegAsync(workspace, args, timeout, ct, onStdOutLine);
    }
}

/// <summary>A theory that needs a real ffmpeg on PATH (skipped, visibly, without one).</summary>
public sealed class FfmpegTheoryAttribute : TheoryAttribute
{
    public FfmpegTheoryAttribute()
    {
        if (!(Environment.GetEnvironmentVariable("PATH") ?? string.Empty)
                .Split(Path.PathSeparator, StringSplitOptions.RemoveEmptyEntries)
                .Any(dir => File.Exists(Path.Combine(dir, "ffmpeg")) || File.Exists(Path.Combine(dir, "ffmpeg.exe"))))
            Skip = "Requires an ffmpeg binary on PATH.";
    }
