    // ── Mix length: the program length bounds sound and picture, not the last sound ──

    [FfmpegFact]
    public async Task A_timeline_whose_last_sound_ends_before_the_picture_keeps_the_full_picture_length()
    {
        // ffmpeg 8.0.1's amix ends at the last sound; a pad after it only sometimes recovers, and the
        // old `-shortest` mux then cut the picture. The race is intermittent, so render several times.
        AssetRef source = Source("tone-short", "color=c=red:s=320x180:r=30", 3, audio: "sine=f=440:sample_rate=48000");
        for (int run = 0; run < 5; run++)
        {
            EditTimeline doc = Doc(Video(Clip(source, 0, 60)), Audio(Clip(source, 0, 6)), Audio(Clip(source, 42, 48)));

            string output = await RenderOk(doc);

            AssertDeliveryFacts(output, 2.0);
            string json = Run("ffprobe", ["-v", "error", "-show_entries", "stream=codec_type,duration", "-of", "json", output]);
            using JsonDocument probe = JsonDocument.Parse(json);
            foreach (JsonElement stream in probe.RootElement.GetProperty("streams").EnumerateArray())
            {
                double duration = double.Parse(stream.GetProperty("duration").GetString()!, CultureInfo.InvariantCulture);
                duration.Should().BeApproximately(2.0, 0.1, $"run {run}: the {stream.GetProperty("codec_type").GetString()} lasts the whole program");
            }
        }
    }

