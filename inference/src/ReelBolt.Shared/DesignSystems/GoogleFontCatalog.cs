using System.Reflection;
using System.Text.Json;
using System.Text.RegularExpressions;

namespace ReelBolt.Shared.DesignSystems;

/// <summary>One font file of a catalogued Google Fonts family.</summary>
/// <param name="File">The file name under the family's directory, e.g. <c>Inter[opsz,wght].ttf</c>.</param>
/// <param name="Style"><c>normal</c> or <c>italic</c>.</param>
/// <param name="Weight">The weight of a static file, or the lowest weight a variable file covers.</param>
/// <param name="WeightMax">Equal to <paramref name="Weight"/> for a static file; the highest weight a variable file covers.</param>
/// <param name="Size">Byte length at the pinned commit.</param>
/// <param name="Sha256">Lowercase hex SHA-256 of the file at the pinned commit.</param>
public sealed record GoogleFontFile(string File, string Style, int Weight, int WeightMax, long Size, string Sha256)
{
    /// <summary>Whether one file covers a range of weights.</summary>
    public bool IsVariable => WeightMax > Weight;

    /// <summary>Whether this file can render <paramref name="weight"/>.</summary>
    public bool Covers(int weight) => weight >= Weight && weight <= WeightMax;
}

/// <summary>One family of the catalog.</summary>
/// <param name="Family">The CSS family name.</param>
/// <param name="License"><c>OFL</c>, <c>APACHE2</c> or <c>UFL</c> (nothing else is catalogued).</param>
/// <param name="Category"><c>sans</c>, <c>serif</c>, <c>mono</c>, <c>display</c> or <c>handwriting</c>.</param>
/// <param name="Directory">The directory under the repository root, e.g. <c>ofl/inter</c>.</param>
/// <param name="Files">The family's files.</param>
public sealed record GoogleFontFamily(string Family, string License, string Category, string Directory, IReadOnlyList<GoogleFontFile> Files);

/// <summary>
/// The checked-in catalog of Google Fonts the engine's <c>StageFont</c> tool may fetch: every family under
/// <c>ofl/</c>, <c>apache/</c> or <c>ufl/</c> of github.com/google/fonts at ONE pinned commit, with each
/// file's size and SHA-256. It is generated by <c>sandbox/scripts/generate-fonts.py</c> and embedded as a
/// resource, so what may be fetched, from where and with what hash is fixed at build time: an agent names a
/// family, never a URL. Every value that later reaches a URL is validated here against a strict pattern, so
/// a corrupted catalog cannot turn into a path traversal or a different host.
/// </summary>
public static class GoogleFontCatalog
{
    private const string ResourceName = "ReelBolt.Shared.DesignSystems.google-fonts-catalog.json";

    private static readonly Regex CommitPattern = new("^[0-9a-f]{40}$", RegexOptions.Compiled);
    private static readonly Regex DirectoryPattern = new("^(ofl|apache|ufl)/[a-z0-9]{1,64}$", RegexOptions.Compiled);
    private static readonly Regex FilePattern = new(@"^[A-Za-z0-9\[\],_.\-]{1,128}\.(ttf|otf)$", RegexOptions.Compiled);
    private static readonly Regex Sha256Pattern = new("^[0-9a-f]{64}$", RegexOptions.Compiled);

    private static readonly Lazy<Loaded> Data = new(Load, LazyThreadSafetyMode.ExecutionAndPublication);

    /// <summary>The google/fonts commit every catalogued path and hash refers to.</summary>
    public static string Commit => Data.Value.Commit;

    /// <summary>Every catalogued family, ordered by name.</summary>
    public static IReadOnlyList<GoogleFontFamily> Families => Data.Value.Families;

    /// <summary>The family called <paramref name="family"/> (case-insensitive, trimmed), or null.</summary>
    public static GoogleFontFamily? Find(string? family) =>
        !string.IsNullOrWhiteSpace(family) && Data.Value.ByName.TryGetValue(family.Trim(), out GoogleFontFamily? found) ? found : null;

    /// <summary>The catalogued family names closest to <paramref name="family"/> (prefix, then substring), at most <paramref name="max"/>.</summary>
    public static IReadOnlyList<string> Suggest(string? family, int max = 5)
    {
        string needle = (family ?? "").Trim();
        if (needle.Length < 2)
            return [];
        List<string> hits = [.. Families.Select(f => f.Family)
            .Where(n => n.Contains(needle, StringComparison.OrdinalIgnoreCase))
            .OrderBy(n => n.StartsWith(needle, StringComparison.OrdinalIgnoreCase) ? 0 : 1)
            .ThenBy(n => n.Length)
            .Take(max)];
        if (hits.Count >= max)
            return hits;

        // Typos: close by edit distance (a transposed, missing or doubled letter).
        int limit = Math.Max(2, needle.Length / 5);
        IEnumerable<string> close = Families.Select(f => f.Family)
            .Where(n => !hits.Contains(n) && Math.Abs(n.Length - needle.Length) <= limit)
            .Select(n => (Name: n, Distance: EditDistance(n.ToLowerInvariant(), needle.ToLowerInvariant(), limit)))
            .Where(x => x.Distance <= limit)
            .OrderBy(x => x.Distance).ThenBy(x => x.Name.Length)
            .Select(x => x.Name);
        hits.AddRange(close.Take(max - hits.Count));
        return hits;
    }

    /// <summary>Levenshtein distance, giving up (returning more than <paramref name="limit"/>) once it must exceed it.</summary>
    private static int EditDistance(string a, string b, int limit)
    {
        int[] prev = new int[b.Length + 1];
        int[] cur = new int[b.Length + 1];
        for (int j = 0; j <= b.Length; j++)
            prev[j] = j;
        for (int i = 1; i <= a.Length; i++)
        {
            cur[0] = i;
            int rowMin = cur[0];
            for (int j = 1; j <= b.Length; j++)
            {
                cur[j] = Math.Min(Math.Min(prev[j] + 1, cur[j - 1] + 1), prev[j - 1] + (a[i - 1] == b[j - 1] ? 0 : 1));
                rowMin = Math.Min(rowMin, cur[j]);
            }
            if (rowMin > limit)
                return limit + 1;
            (prev, cur) = (cur, prev);
        }
        return prev[b.Length];
    }

    private sealed record Loaded(string Commit, IReadOnlyList<GoogleFontFamily> Families, Dictionary<string, GoogleFontFamily> ByName);

    private static Loaded Load()
    {
        using Stream stream = typeof(GoogleFontCatalog).Assembly.GetManifestResourceStream(ResourceName)
            ?? throw new InvalidOperationException($"Embedded resource {ResourceName} is missing.");
        using JsonDocument doc = JsonDocument.Parse(stream);
        JsonElement root = doc.RootElement;

        string commit = root.GetProperty("commit").GetString() ?? "";
        if (!CommitPattern.IsMatch(commit))
            throw new InvalidOperationException("The font catalog commit is not a 40-hex git commit.");

        List<GoogleFontFamily> families = [];
        Dictionary<string, GoogleFontFamily> byName = new(StringComparer.OrdinalIgnoreCase);
        foreach (JsonElement f in root.GetProperty("families").EnumerateArray())
        {
            string name = f.GetProperty("family").GetString() ?? "";
            string directory = f.GetProperty("dir").GetString() ?? "";
            if (!DirectoryPattern.IsMatch(directory))
                throw new InvalidOperationException($"The font catalog directory '{directory}' is not allowed.");

            List<GoogleFontFile> files = [];
            foreach (JsonElement e in f.GetProperty("files").EnumerateArray())
            {
                string file = e.GetProperty("file").GetString() ?? "";
                string sha = e.GetProperty("sha256").GetString() ?? "";
                if (!FilePattern.IsMatch(file) || !Sha256Pattern.IsMatch(sha))
                    throw new InvalidOperationException($"The font catalog entry '{file}' is malformed.");
                files.Add(new GoogleFontFile(file, e.GetProperty("style").GetString() ?? "normal",
                    e.GetProperty("weight").GetInt32(), e.GetProperty("weightMax").GetInt32(), e.GetProperty("size").GetInt64(), sha));
            }

            var family = new GoogleFontFamily(name, f.GetProperty("license").GetString() ?? "", f.GetProperty("category").GetString() ?? "", directory, files);
            families.Add(family);
            byName.TryAdd(name, family);
        }

        return new Loaded(commit, families, byName);
    }
}
