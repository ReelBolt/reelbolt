#!/usr/bin/env bash
# Isolated local ReelBolt stack for the editor-v2 regression suite (e2e/tests/editor-v2).
#
#   e2e/scripts/editor-v2-stack.sh up     [--from <worktree>]   build + start (idempotent)
#   e2e/scripts/editor-v2-stack.sh status [--from <worktree>]   docker compose ps
#   e2e/scripts/editor-v2-stack.sh logs   [--from <worktree>]   tail of workflow-engine, go-api, inference logs
#   e2e/scripts/editor-v2-stack.sh down   [--from <worktree>]   stop and DELETE the stack's volumes
#   e2e/scripts/editor-v2-stack.sh env                          print the local login as shell exports
#
# Everything this stack owns is under compose project `reelbolt-editor-remediation`; the script never
# stops, downs or removes anything outside it. State lives in /tmp/editor-remediation/ (never the repo):
#   stack.env                 generated once, mode 600: random JWT/storage/sandbox/db secrets, local admin
#   garage.toml               per-stack copy of garage/garage.toml.example with random secrets
#   compose.editor-v2.yml     override layered on <worktree>/docker-compose.yml (ports, names, profiles)
#
# Published ports (loopback only, none of them the default stack's):
#   nginx 18080 (http) / 18443 (https), postgres 15432, garage S3 19000, rabbitmq 15674 (amqp) / 15675 (mgmt).
# web (3000/9229), site (3100), whisper (9002) and embeddings (9003) publish nothing here.
# Not started: sandbox-executor/-runtime and autoheal (host-wide side effects), site, docs, mcp, whisper,
# embeddings, and the gpu/fabric/tls profiles. No LLM, transcription or paid provider is configured.
set -euo pipefail

PROJECT=reelbolt-editor-remediation
STATE_DIR=${EDITOR_STACK_STATE_DIR:-/tmp/editor-remediation}
ENV_FILE=$STATE_DIR/stack.env
GARAGE_TOML=$STATE_DIR/garage.toml
OVERRIDE=$STATE_DIR/compose.editor-v2.yml

SCRIPT_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
FROM=$(cd "$SCRIPT_DIR/../.." && pwd)

cmd=${1:-}
shift || true
while [ $# -gt 0 ]; do
  case "$1" in
    --from) FROM=$(cd "$2" && pwd); shift 2 ;;
    *) echo "unknown argument: $1" >&2; exit 2 ;;
  esac
done

die() { echo "editor-v2-stack: $*" >&2; exit 1; }
[ -f "$FROM/docker-compose.yml" ] || die "no docker-compose.yml in $FROM"

hex() { openssl rand -hex "$1"; }

ensure_state() {
  mkdir -p "$STATE_DIR"
  chmod 700 "$STATE_DIR"
  if [ ! -f "$ENV_FILE" ]; then
    umask 077
    # docker-compose.yml makes IMPORT_WORKER_TOKEN mandatory for the import-worker
    # service (`${IMPORT_WORKER_TOKEN:?...}`), so `compose up` refuses to start
    # without it. A caller-supplied value wins; otherwise this stack gets its own
    # throwaway token, like every other secret in this file.
    cat >"$ENV_FILE" <<EOF
# Generated by e2e/scripts/editor-v2-stack.sh for compose project $PROJECT. Local only, never commit.
APP_PORT=18080
HTTPS_PORT=18443
POSTGRES_PORT=15432
MINIO_API_PORT=19000
RABBITMQ_PORT=15674
RABBITMQ_MGMT_PORT=15675
WHISPER_PORT=19002
EMBEDDINGS_PORT=19003
POSTGRES_PASSWORD=$(hex 16)
RABBITMQ_USER=reelbolt
RABBITMQ_PASSWORD=$(hex 16)
JWT_SIGNING_KEY=$(hex 32)
SANDBOX_API_TOKEN=$(hex 32)
INTERNAL_API_TOKEN=$(hex 32)
IMPORT_WORKER_TOKEN=${IMPORT_WORKER_TOKEN:-$(hex 32)}
MINIO_ACCESS_KEY=GK$(hex 12)
MINIO_SECRET_KEY=$(hex 32)
MINIO_BUCKET=reelforge
BILLING_ENABLED=false
SIGNUP_ENABLED=false
ADMIN_EMAIL=admin@editor-remediation.local
ADMIN_PASSWORD=$(hex 12)Aa1!
PUBLIC_BASE_URL=http://localhost:18080
WEB_BUILD_TARGET=production
WEB_NODE_ENV=production
STARTUP_CLEANUP_PURGE_QUEUES=true
PLATFORM_DOCS_ENABLED=false
EOF
    chmod 600 "$ENV_FILE"
  fi
  if [ ! -f "$GARAGE_TOML" ]; then
    umask 077
    sed -e "s/^rpc_secret = .*/rpc_secret = \"$(hex 32)\"/" \
        -e "s|^admin_token = .*|admin_token = \"$(openssl rand -base64 32)\"|" \
        -e "s|^metrics_token = .*|metrics_token = \"$(openssl rand -base64 32)\"|" \
        "$FROM/garage/garage.toml.example" >"$GARAGE_TOML"
    # garage runs as a non-root uid inside the container and must read the bind mount.
    chmod 644 "$GARAGE_TOML"
  fi
  cat >"$OVERRIDE" <<EOF
# Generated by e2e/scripts/editor-v2-stack.sh; layered on docker-compose.yml for project $PROJECT.
services:
  postgres:
    container_name: !reset null
    ports: !override
      - "127.0.0.1:\${POSTGRES_PORT}:5432"
  garage:
    ports: !override
      - "127.0.0.1:\${MINIO_API_PORT}:3900"
    volumes: !override
      - $GARAGE_TOML:/etc/garage.toml:ro
      - garagedata:/data
      - garagemeta:/meta
  rabbitmq:
    ports: !override
      - "127.0.0.1:\${RABBITMQ_PORT}:5672"
      - "127.0.0.1:\${RABBITMQ_MGMT_PORT}:15672"
  qdrant:
    volumes: !override
      - qdrantdata:/qdrant/storage
  inference:
    build:
      network: ${BUILD_NETWORK}
  workflow-engine:
    build:
      network: ${BUILD_NETWORK}
  go-api:
    build:
      network: ${BUILD_NETWORK}
  import-worker:
    build:
      network: ${BUILD_NETWORK}
  web:
    build:
      network: ${BUILD_NETWORK}
    ports: !reset []
    environment:
      - NODE_ENV=production
      - NODE_OPTIONS=
  nginx:
    build:
      network: ${BUILD_NETWORK}
    labels: !reset {}
    ports: !override
      - "127.0.0.1:\${APP_PORT}:80"
      - "127.0.0.1:\${HTTPS_PORT}:443"
    depends_on: !override
      web:
        condition: service_healthy
        restart: true
      go-api:
        condition: service_healthy
        restart: true
      inference:
        condition: service_healthy
        restart: true
      workflow-engine:
        condition: service_healthy
        restart: true
  whisper:
    profiles: !override ["editor-v2-off"]
    ports: !override
      - "127.0.0.1:\${WHISPER_PORT}:8000"
  embeddings:
    profiles: !override ["editor-v2-off"]
    ports: !override
      - "127.0.0.1:\${EMBEDDINGS_PORT}:80"
  site:
    profiles: !override ["editor-v2-off"]
    ports: !reset []
  docs:
    profiles: !override ["editor-v2-off"]
  mcp:
    profiles: !override ["editor-v2-off"]
  # Never in this stack: the executor deletes host sandbox containers and creates the global
  # sandbox-net at startup; autoheal restarts any labelled container on the host.
  sandbox-executor:
    profiles: !override ["editor-v2-forbidden"]
  sandbox-runtime:
    profiles: !override ["editor-v2-forbidden"]
  autoheal:
    profiles: !override ["editor-v2-forbidden"]
volumes:
  qdrantdata:
EOF
}

# BuildKit's resolver cannot reach this host's DNS on the default bridge; `host` works around it.
BUILD_NETWORK=${EDITOR_STACK_BUILD_NETWORK:-host}

# Compose reads the caller's shell environment before --env-file, so a provider key exported in that
# shell would reach the stack (audit D9: no LLM or paid provider here). Drop every one of them first.
scrub_provider_env() {
  local v
  for v in $(compgen -e); do
    case "$v" in
      ANTHROPIC_*|AZURE_OPENAI_*|OPENAI_*|GEMINI_*|DEEPSEEK_*|HF_*|FAL_*|MINIMAX_*) unset "$v" ;;
    esac
  done
}

compose() {
  scrub_provider_env
  docker compose -p "$PROJECT" --project-directory "$FROM" --env-file "$ENV_FILE" \
    -f "$FROM/docker-compose.yml" -f "$OVERRIDE" "$@"
}

check_ports() {
  # Refuse to start if a port is taken by anything that is not this project.
  local mine p
  mine=$(docker ps --filter "label=com.docker.compose.project=$PROJECT" --format '{{.Ports}}')
  for p in 18080 18443 15432 19000 15674 15675; do
    if ss -ltnH 2>/dev/null | awk '{print $4}' | grep -qE "[:.]$p\$" && ! grep -q ":$p->" <<<"$mine"; then
      die "port $p is already in use by something outside $PROJECT; free it or stop that process yourself"
    fi
  done
}

wait_http() {
  local url=$1 tries=${2:-90}
  for _ in $(seq "$tries"); do
    if curl -fsS -o /dev/null "$url"; then return 0; fi
    sleep 2
  done
  die "timed out waiting for $url"
}

case "$cmd" in
  up)
    command -v docker >/dev/null || die "docker not found"
    ensure_state
    check_ports
    echo "editor-v2-stack: building and starting $PROJECT from $FROM"
    if [ -n "${EDITOR_STACK_BUILD_BUILDER:-}" ]; then
      # `compose up` has no --builder, so build with the named one explicitly and
      # start without building. CI uses this for its entitled builder.
      compose build --builder "$EDITOR_STACK_BUILD_BUILDER"
      compose up -d --no-build --wait --wait-timeout 900
    else
      compose up -d --build --wait --wait-timeout 900
    fi
    wait_http "http://127.0.0.1:18080/api/v1/health"
    wait_http "http://127.0.0.1:18080/app/login"
    echo "editor-v2-stack: up at http://localhost:18080/app (login: $0 env)"
    ;;
  status)
    [ -f "$OVERRIDE" ] || ensure_state
    compose ps
    ;;
  down)
    [ -f "$OVERRIDE" ] || ensure_state
    compose down -v --remove-orphans
    ;;
  logs)
    [ -f "$OVERRIDE" ] || ensure_state
    compose logs --no-color --tail "${EDITOR_STACK_LOG_TAIL:-400}" workflow-engine go-api inference
    ;;
  env)
    [ -f "$ENV_FILE" ] || die "no $ENV_FILE yet; run '$0 up' first"
    # shellcheck disable=SC1090
    . "$ENV_FILE"
    echo "export EDITOR_E2E_BASE_URL=http://localhost:${APP_PORT}"
    echo "export EDITOR_E2E_EMAIL='${ADMIN_EMAIL}'"
    echo "export EDITOR_E2E_PASSWORD='${ADMIN_PASSWORD}'"
    ;;
  *)
    sed -n '2,9p' "$0" >&2
    exit 2
    ;;
esac
