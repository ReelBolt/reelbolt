  await expect(page.getByTestId('metadata-value-bitrate')).toContainText('3.36 Mbps');

  // The container is ffprobe's own probe LIST, shown verbatim rather than reduced to "mp4".
  const container = await page.getByTestId('metadata-value-container').textContent();
  expect(container).toContain('mp4');
  expect(container).toContain('mov');
  expect(container).toContain('mj2');
  expect(container?.trim()).not.toBe('mp4');

  // ── The never-analysed clip: a stated absence, not zeros ───────────────────
  await tileOf(page, REF_UNANALYSED).click();
  await expect(page.getByTestId('metadata-not-analysed')).toBeVisible();
  await expect(page.getByTestId('metadata-not-analysed')).toContainText('Not analysed');

  // ── The pre-T-105 artifact: probe present, all six appended fields null ────
  await tileOf(page, REF_PRE_PROBE).click();
  await expect(page.getByTestId('metadata-pre-probe-artifact')).toBeVisible();
  await expect(page.getByTestId('metadata-not-analysed')).toHaveCount(0);

  for (const key of ['codec', 'channels', 'sampleRate', 'bitrate']) {
    // R05.8: a row with no value is not shown at all (it used to read "Not probed"); the gap note names it.
    await expect(page.getByTestId(`metadata-value-${key}`)).toHaveCount(0);
  }

  // The container row falls back to the DECLARED MIME type, and says that is what it is.
  await expect(page.getByTestId('metadata-value-container')).toContainText('declared MIME type');

  // ── No fabricated zero, anywhere, on either panel state ────────────────────
  // Exact-value checks rather than substrings: "30 fps (30 fps)" legitimately contains "0 fps", so
  // a substring sweep would report a bug that is not there and hide the one that would be.
  await expect(page.getByTestId('metadata-panel')).not.toContainText('0 channels');
  await expect(page.getByTestId('metadata-panel')).not.toContainText('0 bps');
  await expect(page.getByTestId('metadata-panel')).not.toContainText('0 kHz');
  await expect(page.getByTestId('metadata-panel')).not.toContainText('0 Hz');
  await expect(page.getByTestId('metadata-panel')).not.toContainText('unknown codec');
  await expect(page.getByTestId('metadata-gap-note')).toContainText(/Not measured for this file, so not shown:.*Codec.*Audio channels.*Sample rate.*Bitrate/);
