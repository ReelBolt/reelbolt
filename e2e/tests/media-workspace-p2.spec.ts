interface StubLog {
  method: string;
  pathname: string;
}

/**
 * Serves the video fixture exactly as an S3-compatible object store does: `Accept-Ranges: bytes`
 * plus a real `206` with `Content-Range` for a ranged request.
 *
 * This matters for the marks test. A plain `200` with the whole body leaves Chromium treating the
 * resource as unseekable until it is fully buffered, so `video.currentTime = 3` silently clamps to
 * 0 and the test would "pass" a seek it never performed.
 */
function fulfillVideo(route: Route) {
  const body = fs.readFileSync(VIDEO_FIXTURE);
  const range = route.request().headers()['range'];

  if (!range) {
    return route.fulfill({
      status: 200,
      contentType: 'video/mp4',
      headers: { 'Accept-Ranges': 'bytes', 'Content-Length': String(body.length) },
      body,
    });
  }

  const match = /bytes=(\d+)-(\d*)/.exec(range);
  if (!match) return route.fulfill({ status: 416, body: '' });

  const start = Number(match[1]);
  const end = match[2] ? Number(match[2]) : body.length - 1;
  const slice = body.subarray(start, end + 1);

  return route.fulfill({
    status: 206,
    contentType: 'video/mp4',
    headers: {
      'Accept-Ranges': 'bytes',
      'Content-Range': `bytes ${start}-${end}/${body.length}`,
      'Content-Length': String(slice.length),
    },
    body: slice,
  });
}

/**
 * Intercepts every `/api/v1/**` call the workspace makes and answers it from the fixtures above.
 *
 * Records every request so a test can assert the UI issued **no write**, and so the sheet request can
 * be asserted to have really happened (a `background-image` that never loaded would otherwise look
 * identical in the DOM).
 */
async function stubMediaApi(page: Page): Promise<StubLog[]> {
  const log: StubLog[] = [];

  await page.route('**/api/v1/**', async (route: Route) => {
    const request = route.request();
    const url = new URL(request.url());
    const pathname = url.pathname;
    log.push({ method: request.method(), pathname });

    const json = (body: unknown, status = 200) =>
      route.fulfill({ status, contentType: 'application/json', body: JSON.stringify(body) });

    // Order matters: the more specific paths are matched before the pool path they are nested under.
    if (pathname.endsWith('/media/derivatives/request')) {
      // The 202 body is the schema's own shape (`MediaRef`, `kinds[]`, `requestedBy`) — the panel
      // renders `kinds.length`, and a body missing it is a malformed stub rather than a UI defect.
      const body = JSON.parse(request.postData() ?? '{}') as { mediaRef?: string };
      return json(
        {
          mediaRef: body.mediaRef ?? REF_FULL,
          kinds: ['proxy', 'filmstrip', 'waveformPeaks', 'keyframeIndex'],
          requestedBy: 'editor-open',
        },
        202,
      );
    }

    if (/\/media\/derivatives\/[^/]+\/sheet\/\d+\/content$/.test(pathname)) {
      return route.fulfill({
        status: 200,
        contentType: 'image/png',
        body: fs.readFileSync(sheetPngPath),
      });
    }

    if (pathname.endsWith(`/edit-timelines/${TIMELINE_ID}`) && request.method() === 'GET') return json(emptyTimeline);
    if (pathname.endsWith(`/edit-timelines/${TIMELINE_ID}/history`)) return json({ id: TIMELINE_ID, currentRevision: 1, entries: [], restorableRevisions: [1] });
    if (/\/media\/derivatives\/[^/]+\/content$/.test(pathname)) return fulfillVideo(route);
    if (/\/files\/[^/]+\/content$/.test(pathname)) return fulfillVideo(route);

    if (/\/media\/[^/]+\/derivatives$/.test(pathname)) return json(derivatives);
    if (/\/media\/[^/]+\/filmstrip$/.test(pathname)) return json(filmstrip);
    if (/\/media\/bins\/[^/]+\/items$/.test(pathname)) return json([]);
    if (pathname.endsWith('/media/bins')) return json(bins);
    if (pathname.endsWith('/media')) return json(pool);

    return json({}, 404);
  });

  return log;
}

async function openWorkspace(page: Page) {
  // A client-side exception is the one failure mode an assertion on a missing test id reports as
  // "element not found". Loud on the console so a crash is never mistaken for a slow render.
  page.on('pageerror', (error) => {
    console.log(`[pageerror] ${error.message}`);
    console.log(error.stack ?? '(no stack)');
  });
  page.on('console', (message) => {
    if (message.type() === 'error') console.log(`[console.error] ${message.text()}`);
  });

  const user = encodeURIComponent(
    JSON.stringify({ email: 'qa@example.com', isAdmin: false, mustChangePassword: false }),
  );

  await page.context().addCookies([
    { name: 'reelbolt_token', value: 'qa-stub-token', url: BASE_URL },
    { name: 'reelbolt_user', value: user, url: BASE_URL },
  ]);

  await page.goto(`${BASE_URL}${WORKSPACE_PATH}`);
  await page.getByTestId('workspace-media').click();
  await expect(page.getByTestId('media-pool')).toBeVisible();
}

const tileOf = (page: Page, mediaRef: string) =>
  page.locator(`[data-testid="media-clip-tile"][data-media-ref="${mediaRef}"]`);

/** Seeks the mounted `<video>` to `seconds` and waits for the element to report the seek done. */
async function seekTo(page: Page, seconds: number) {
  await page.waitForFunction(() => {
    const video = document.querySelector('video');
    return !!video && video.readyState >= 1 && video.duration > 0;
  });

  await page.evaluate(async (target: number) => {
    const video = document.querySelector('video');
    if (!video) throw new Error('no <video> mounted');

    const done = new Promise<void>((resolve) =>
      video.addEventListener('seeked', () => resolve(), { once: true }),
    );
    video.currentTime = target;
    await done;
  }, seconds);
}

