// ─────────────────────────────────────────────────────────────────────────────
// 1b. Hover-scrub — the assertion this wave's browser check exists for.
//
//     This is the test that FAILED the wave. It is kept, not deleted and not weakened, because it
//     is the only assertion in the repository that sees the whole journey: the strip's subject must
//     survive the pointer LEAVING the tile, which no jsdom test produces on its own. Two causes
//     were behind its failure and this test is sensitive to both, so it is the regression guard for
//     each — cause 1 (the tile cleared the subject on `mouseleave`) and cause 2 (an unbounded tile
//     list pushed the cell below the fold, where `page.mouse.move` cannot reach it because it never
//     scrolls).
// ─────────────────────────────────────────────────────────────────────────────

test('hover-scrub reaches a different real thumbnail through the tile-to-strip journey', async ({ page }) => {
  // The timeline shares the screen with the pool in the editor, so the pool pane is short: a tall window keeps the tile and the strip on screen together.
  await page.setViewportSize({ width: 1280, height: 1400 });
  await stubMediaApi(page);
  await openWorkspace(page);

  // The premise: the cell exists while the TILE is hovered.
  await tileOf(page, REF_FULL).hover();
  const cell = page.getByTestId('filmstrip-cell');
  await expect(cell).toBeVisible();
  await expect(cell).toHaveAttribute('data-thumb-index', '0');

  const cellBox = await cell.boundingBox();
  if (!cellBox) throw new Error('the filmstrip cell has no box');

  // CAUSE 2, asserted directly and separately from the pointer journey below: the cell must be
  // REACHABLE, not merely mounted. `toBeVisible` does not imply a pointer can get there — an
  // element below the fold has a non-empty box and passes it — so this asks the browser the only
  // question that settles it: what is actually at the cell's own centre? A cell pushed out of the
  // viewport answers `null` here, and that is precisely how the second cause presented.
  //
  // jsdom cannot express this at all (no layout, every rectangle is zero), which is why the wave's
  // unit suites were green while the control was unusable.
  const atCellCentre = await cell.evaluate((element) => {
    const box = element.getBoundingClientRect();
    const x = box.left + box.width / 2;
    const y = box.top + box.height / 2;
    const hit = document.elementFromPoint(x, y);
    return {
      y: Math.round(y),
      viewportHeight: window.innerHeight,
      hitTestId: hit instanceof Element ? hit.getAttribute('data-testid') : null,
      dbg: hit instanceof Element ? hit.outerHTML.slice(0, 300) + ' PARENT ' + (hit.parentElement?.outerHTML.slice(0, 200) ?? '') : 'none',
    };
  });
  expect(atCellCentre.y).toBeLessThan(atCellCentre.viewportHeight);
  expect(atCellCentre.hitTestId, JSON.stringify(atCellCentre)).toBe('filmstrip-cell');

  const startPosition = await cell.evaluate((element) => getComputedStyle(element).backgroundPosition);

  // A GRADUAL pointer move from the tile onto the strip — what a user does to scrub it.
  await page.mouse.move(cellBox.x + cellBox.width * 0.9, cellBox.y + cellBox.height / 2, {
    steps: 25,
  });

  // WHAT SHOULD HAPPEN: the strip still describes this clip, and the position has moved to a
  // different real thumbnail.
  const position = page.getByTestId('filmstrip-position');
  await expect(position).toBeVisible();
  await expect(cell).not.toHaveAttribute('data-thumb-index', '0');
  await expect(position).toContainText(`thumbnail ${await cell.getAttribute('data-thumb-index')}`);
  expect(await cell.evaluate((element) => getComputedStyle(element).backgroundPosition)).not.toBe(
    startPosition,
  );
});

