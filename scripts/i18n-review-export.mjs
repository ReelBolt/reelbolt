#!/usr/bin/env node
// Exports the Italian strings for owner review: docs/i18n-review/it.md.
//   node scripts/i18n-review-export.mjs        (npm run i18n:review in web/)
// Reads web/messages and site/messages (en + it) and each app's it/_flags.json ({"ns.key": "reason"}).
// One section per app + namespace; a table (key | English | Italian | flag reason); flagged rows first.
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const apps = ['web', 'site'];

function flatten(value, prefix, out = {}) {
  if (value && typeof value === 'object' && !Array.isArray(value)) {
    for (const [k, v] of Object.entries(value)) flatten(v, prefix ? `${prefix}.${k}` : k, out);
  } else out[prefix] = value;
  return out;
}

function namespaces(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir).filter((f) => f.endsWith('.json') && !f.startsWith('_')).sort();
}

const cell = (v) =>
  String(v ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/\|/g, '\\|')
    .replace(/\r?\n/g, ' ');

let out = '# Italian review\n\n';
out += 'Generated by `node scripts/i18n-review-export.mjs` from `web/messages` and `site/messages`. Do not edit by hand.\n';
out += 'Flagged rows (strings the translator was unsure about, from `messages/it/_flags.json`) come first in each section.\n\n';

let total = 0;
const flaggedOut = {};  // `${app} / ${ns}` -> rows
const unmatchedFlags = [];  // flags that point at no catalogue key (a stale or mistyped flag)
let flaggedTotal = 0;
for (const app of apps) {
  const enDir = join(root, app, 'messages', 'en');
  const itDir = join(root, app, 'messages', 'it');
  const flagsFile = join(itDir, '_flags.json');
  const flags = existsSync(flagsFile) ? JSON.parse(readFileSync(flagsFile, 'utf8')) : {};
  // Area lanes write their own file: messages/it/_flags/<area>.json (no shared file, no merge conflicts).
  const flagsDir = join(itDir, '_flags');
  if (existsSync(flagsDir)) {
    for (const f of readdirSync(flagsDir).filter((n) => n.endsWith('.json')).sort()) {
      Object.assign(flags, JSON.parse(readFileSync(join(flagsDir, f), 'utf8')));
    }
  }
  const usedFlags = new Set();
  /** A flag names a leaf key or a PREFIX: every leaf under `prefix.` carries the flag. */
  const flagFor = (key) => {
    if (Object.prototype.hasOwnProperty.call(flags, key)) { usedFlags.add(key); return flags[key]; }
    let best;
    for (const fk of Object.keys(flags)) if (key.startsWith(`${fk}.`) && (best === undefined || fk.length > best.length)) best = fk;
    if (best !== undefined) { usedFlags.add(best); return flags[best]; }
    return undefined;
  };
  for (const file of namespaces(enDir)) {
    const ns = file.slice(0, -5);
    const en = flatten(JSON.parse(readFileSync(join(enDir, file), 'utf8')), ns);
    const itPath = join(itDir, file);
    const it = existsSync(itPath) ? flatten(JSON.parse(readFileSync(itPath, 'utf8')), ns) : {};
    const rows = Object.keys(en).map((key) => ({ key, en: en[key], it: it[key], flag: flagFor(key) }));
    rows.sort((a, b) => Number(Boolean(b.flag)) - Number(Boolean(a.flag)) || a.key.localeCompare(b.key));
    total += rows.length;
    flaggedTotal += rows.filter((r) => r.flag).length;
    const fr = rows.filter((r) => r.flag);
    if (fr.length) flaggedOut[`${app} / ${ns}`] = fr;
    out += `## ${app} / ${ns}\n\n| Key | English | Italian | Flag |\n|---|---|---|---|\n`;
    for (const r of rows) out += `| \`${r.key}\` | ${cell(r.en)} | ${cell(r.it)} | ${cell(r.flag)} |\n`;
    out += '\n';
  }
  for (const fk of Object.keys(flags)) if (!usedFlags.has(fk)) unmatchedFlags.push({ app, key: fk, reason: flags[fk] });
}
out += `---\n${total} strings, ${flaggedTotal} flagged.\n`;

const dest = join(root, 'docs', 'i18n-review', 'it.md');
mkdirSync(dirname(dest), { recursive: true });
writeFileSync(dest, out);
console.log(`wrote ${dest} (${total} strings, ${flaggedTotal} flagged)`);

// The short list to read first: only the strings a translator flagged, plus the e-mail flags (not in a catalogue).
let fl = '# Italian review: flagged strings only\n\n';
fl += 'Generated by `node scripts/i18n-review-export.mjs`. Do not edit by hand. Read this file first; `it.md` has every string.\n';
fl += 'Each row: key, English, Italian, and why the translator was unsure. Mark a decision in a copy of this file or send the corrected Italian.\n\n';
const areas = Object.keys(flaggedOut).sort();
for (const a of areas) {
  fl += `## ${a} (${flaggedOut[a].length})\n\n| Key | English | Italian | Why flagged |\n|---|---|---|---|\n`;
  for (const r of flaggedOut[a]) fl += `| \`${r.key}\` | ${cell(r.en)} | ${cell(r.it)} | ${cell(r.flag)} |\n`;
  fl += '\n';
}
if (unmatchedFlags.length) {
  fl += `## flags that match no catalogue key (${unmatchedFlags.length})\n\nThese flags point at a key that does not exist (renamed or removed); the string they meant is NOT listed above. Fix the flag file.\n\n| App | Flag key | Why flagged |\n|---|---|---|\n`;
  for (const u of unmatchedFlags) fl += `| ${u.app} | \`${cell(u.key)}\` | ${cell(u.reason)} |\n`;
  fl += '\n';
  console.warn(`warning: ${unmatchedFlags.length} flag(s) match no catalogue key`);
}
const mailFlags = join(root, 'api', 'services', 'email_templates', 'it', '_flags.json');
if (existsSync(mailFlags)) {
  const m = JSON.parse(readFileSync(mailFlags, 'utf8'));
  fl += `## e-mail templates (${Object.keys(m).length})\n\nTemplates are in \`api/services/email_templates/it/\` (subjects in \`subjects.json\`).\n\n| Item | Why flagged |\n|---|---|\n`;
  for (const [k, v] of Object.entries(m)) fl += `| \`${cell(k)}\` | ${cell(v)} |\n`;
  fl += '\n';
}
const docFlagsDir = join(root, 'docs', 'i18n-review', 'docs-it-flags');
if (existsSync(docFlagsDir)) {
  const files = readdirSync(docFlagsDir).filter((f) => f.endsWith('.md')).sort();
  fl += `## user guide (docs/i18n-review/docs-it-flags/, ${files.length} files)\n\n`;
  for (const f of files) fl += `- [${f}](./docs-it-flags/${f})\n`;
  fl += '\n';
}
const flDest = join(root, 'docs', 'i18n-review', 'it-flagged.md');
writeFileSync(flDest, fl);
console.log(`wrote ${flDest} (${areas.length} areas)`);
